cmd_inventory() {
  [ $# -eq 2 ] || die "usage: inventory vX vY"
  local vx="$1" vy="$2"
  require_fw
  require_project_root
  require_tag "${vx}"
  require_tag "${vy}"
  require_t
  local d="${WORK}/inventory"
  rm -rf "${d}" && mkdir -p "${d}" || die "cannot prepare ${d}"
  local releases
  releases="$(releases_between "${vx}" "${vy}" | tr '\n' ' ')"
  # A renamed file's old path is no deletion: edge case 2 handles it, after the loop.
  renames_between "${vx}" "${vy}" > "${d}/renames"
  # The answers a release in between moved: their old file is edge case 8's, not 7's.
  moved_here "${vx}" "${vy}" "${d}/moved"

  section "Files — class, the framework vX->vY (=, M, A, D), the project against the tags, the 3-way's measure"
  local path class bx by bp fwst prj measure n mine base theirs r prev changed modey modep
  { awk -F'\t' '{print $2}' "$(tree_of "${vx}")"; awk -F'\t' '{print $2}' "$(tree_of "${vy}")"; } | sort -u > "${d}/paths"
  while IFS= read -r path; do
    class="$(classify "${path}")"
    case "${class}" in
      PROJECT-MEMORY | LOCAL | GRAFT-STATE) continue ;;
      NONE) fail "no class for ${path} (a payload file of ${vx} or ${vy})"; continue ;;
    esac
    bx="$(blob_at "${vx}" "${path}")"
    by="$(blob_at "${vy}" "${path}")"
    if [ -z "${bx}" ]; then fwst=A; elif [ -z "${by}" ]; then fwst=D; elif [ "${bx}" = "${by}" ]; then fwst="="; else fwst=M; fi
    # LEARNINGS.md: only its header region is the framework's.
    if [ "${class}" = LEARNINGS ]; then
      lf "${path}" 2>/dev/null | header_region /dev/stdin > "${d}/lrn.mine"
      fw show "${vx}:${path}" | header_region /dev/stdin > "${d}/lrn.base"
      fw show "${vy}:${path}" | header_region /dev/stdin > "${d}/lrn.theirs"
      if cmp -s "${d}/lrn.base" "${d}/lrn.theirs"; then fwst="="; else fwst=M; fi
      if cmp -s "${d}/lrn.mine" "${d}/lrn.theirs"; then prj="=vY"; elif cmp -s "${d}/lrn.mine" "${d}/lrn.base"; then prj="=vX"; else prj=diverged; fi
      mine="${d}/lrn.mine"; base="${d}/lrn.base"; theirs="${d}/lrn.theirs"
    else
      if [ -f "${path}" ]; then
        bp="$(pg hash-object -- "${path}")"
        if [ "${bp}" = "${by}" ]; then prj="=vY"; elif [ "${bp}" = "${bx}" ]; then prj="=vX"; else prj=diverged; fi
        lf "${path}" > "${d}/mine"
      else
        prj=absent
      fi
      mine="${d}/mine"; base="${d}/base"; theirs="${d}/theirs"
      [ "${fwst}" = M ] && { fw show "${vx}:${path}" > "${base}"; fw show "${vy}:${path}" > "${theirs}"; }
    fi
    measure=""
    if [ "${fwst}" = M ] && [ "${prj}" = diverged ]; then
      pg merge-file -p "${mine}" "${base}" "${theirs}" > "${d}/merged" 2>/dev/null
      n=$?
      measure="3-way: ${n} conflict(s), $(conflict_lines "${d}/merged") of $(wc -l < "${d}/merged" | tr -d ' ') lines in conflict"
    fi
    [ "${class}" = LEARNINGS ] && path="${path} (header)"
    info "$(printf '%-9s %-2s %-9s %s%s' "${class}" "${fwst}" "${prj}" "${path}" "${measure:+ — ${measure}}")"
    path="${path% (header)}"
    # The flags of the edge cases (SETUP.md, *Edge cases*).
    if [ "${class}" = METHOD ] && [ "${prj}" = diverged ] && [ "${fwst}" != D ]; then
      # Edge case 8 for a file whose moved slots the project answered, or one whose moved slot
      # is a value (moved_value): a diverged copy whose moved slots, all marked lines, are
      # all open holds a customisation, edge case 7's.
      if moved_answered "${d}/moved" "${path}" "${vx}"; then
        check "edge case 8: ${path} is METHOD in ${vy} and the project answered slots of it a release moved (below): carry them first, then bring it over — a customisation beyond its slots is edge case 7's"
      elif moved_value "${d}/moved" "${path}"; then
        if [ -n "$(moved_value_elsewhere "${d}/moved" "${path}" "${vx}" "${d}/flag" | head -n 1)" ]; then
          check "edge case 8: ${path} is METHOD in ${vy}, and a release in between moved its value to another file (below): its line holds the default, but the project sets the variable elsewhere — read the CHECK below before bringing it over; a customisation beyond its slots is edge case 7's"
        else
          check "edge case 8: ${path} is METHOD in ${vy}, and a release in between moved its value to another file (below): the value is the default, nothing to carry — bring it over; a customisation beyond its slots is edge case 7's"
        fi
      elif in_list "${d}/moved.unknown" "${path}"; then
        check "edge case 8: ${path} is METHOD in ${vy}, and a release in between moved its slots in a form this check does not know (below): carry its answers by hand first, then bring it over — a customisation beyond its slots is edge case 7's"
      else
        check "edge case 7: ${path} is METHOD but customised in the project — reconcile it as a HYBRID (3-way), never overwrite"
      fi
    fi
    [ "${fwst}" = D ] && [ "${prj}" != absent ] && [ -z "$(renamed_to "${d}/renames" "${path}")" ] \
      && check "edge case 1: ${path} is deleted in ${vy} — remove it from the project (git rm), after checking it holds nothing of the project's"
    [ "${fwst}" = A ] && [ "${prj}" = diverged ] && check "${path} is new in ${vy}, but the project already has a file there: compare before taking ${vy}'s"
    [ "${path}" = .gitignore ] && [ "${fwst}" = M ] && info "  .gitignore: an additive union (Step 3), not a 3-way"
    if [ "${fwst}" = M ]; then
      changed=""; prev="${vx}"
      for r in ${releases}; do
        [ "$(version_id "${prev}" "${path}")" = "$(version_id "${r}" "${path}")" ] || changed="${changed} ${r}"
        prev="${r}"
      done
      [ "$(echo ${changed} | wc -w | tr -d ' ')" -gt 1 ] \
        && check "edge case 6: ${path} changed in${changed} — if its 3-way is intricate, reconcile one release at a time"
    fi
    if [ -n "${by}" ] && [ -f "${path}" ]; then
      modey="$(mode_at "${vy}" "${path}")"
      modep="$(mode_of "${path}")"
      [ "${modey}" = "${modep}" ] || check "${path}: ${vy}'s mode is ${modey}, the project's ${modep} (chmod after the copy, on Windows git update-index --chmod: Step 3)"
    fi
  done < "${d}/paths"
  # Edge case 2: each rename, by what the project holds at the old path. A customised copy
  # is merged into the new path (base the old path at vX, theirs the new one at vY), and
  # its measure is shown as for any other 3-way.
  local old new
  while IFS=$'\t' read -r old new; do
    if [ ! -f "${old}" ]; then
      check "edge case 2: renamed between ${vx} and ${vy}: ${old} -> ${new} — the project holds no ${old}: bring ${new} over from ${vy}"
    elif [ "$(pg hash-object -- "${old}")" = "$(blob_at "${vx}" "${old}")" ]; then
      check "edge case 2: renamed between ${vx} and ${vy}: ${old} -> ${new} — the project's copy is ${vx}'s: bring ${new} over from ${vy}, then git rm ${old}"
    else
      fw show "${vx}:${old}" > "${d}/rename.base"
      fw show "${vy}:${new}" > "${d}/rename.theirs"
      lf "${old}" > "${d}/rename.mine"
      pg merge-file -p "${d}/rename.mine" "${d}/rename.base" "${d}/rename.theirs" > "${d}/rename.merged" 2>/dev/null
      n=$?
      check "edge case 2: renamed between ${vx} and ${vy}: ${old} -> ${new} — customised in the project: merge it into ${new} (base ${vx}:${old}, theirs ${vy}:${new}), then git rm ${old}; 3-way: ${n} conflict(s), $(conflict_lines "${d}/rename.merged") of $(wc -l < "${d}/rename.merged" | tr -d ' ') lines in conflict"
    fi
  done < "${d}/renames"

  section "Markers — slots added or removed between ${vx} and ${vy}, line by line"
  local added="" removed="" na nr from
  while IFS= read -r path; do
    case "$(classify "${path}")" in METHOD | HYBRID | TEMPLATE | LEARNINGS) ;; *) continue ;; esac
    # A renamed file is compared with its old path, under its new name.
    [ -n "$(renamed_to "${d}/renames" "${path}")" ] && continue
    from="$(renamed_from "${d}/renames" "${path}")"
    marker_lines "${vx}" "${from:-${path}}" > "${d}/markers.x"
    marker_lines "${vy}" "${path}" > "${d}/markers.y"
    na="$(LC_ALL=C comm -13 "${d}/markers.x" "${d}/markers.y" | wc -l | tr -d ' ')"
    nr="$(LC_ALL=C comm -23 "${d}/markers.x" "${d}/markers.y" | wc -l | tr -d ' ')"
    [ "${na}" -gt 0 ] && added="${added} ${path}(+${na})"
    [ "${nr}" -gt 0 ] && removed="${removed} ${path}(-${nr})"
  done < "${d}/paths"
  if [ -n "${added}" ] && [ -n "${removed}" ]; then
    check "markers removed in${removed} and added in${added}: a slot may have MOVED — if the project answered it in the old file, carry the answer to the new one first (edge case 8)"
  elif [ -n "${added}" ]; then
    check "new slots in${added}: fill them with the project's answers (Step 4)"
  elif [ -n "${removed}" ]; then
    info "slots removed in${removed}"
  else
    ok "no slot added or removed"
  fi

  section "Answers a release in between moved to another file (edge case 8) — each answered one to carry first"
  local rel old line new label default ans elsewhere
  [ -s "${d}/moved" ] || [ -s "${d}/moved.unknown" ] || ok "no release between ${vx} and ${vy} moved a slot"
  while IFS=$'\t' read -r rel old line new label default; do
    if [ ! -f "${old}" ] || slot_open "${line}" "${old}"; then
      elsewhere=""
      [ -z "${default}" ] || elsewhere="$(value_elsewhere "${line}" "${new}" "${vx}" "${new}" "${d}/elsewhere" | head -n 1)"
      if [ -n "${elsewhere}" ]; then
        check "edge case 8: ${old}: '$(short "${line}")' is open, but the project's ${new} sets the variable on a line of its own ('$(clip "$(short "${elsewhere}")")'): that value may be the project's — carry it to ${new}'s line that opens with '${label}'"
      else
        info "${old}: '$(short "${line}")' is open in the project: nothing to carry"
      fi
      continue
    fi
    if [ -n "${default}" ]; then
      ans="$(value_at "${line}" "${default}" "${old}")"
      if [ -n "${ans}" ]; then
        check "edge case 8: ${old}: the value of '$(short "${line}")' is the project's ('$(clip "${ans}")') — ${rel} moved it: carry it to ${new}, the line that opens with '${label}', before ${old} is reconciled"
      else
        check "edge case 8: ${old}: the line '$(short "${line}")' has another form in the project — ${rel} moved its value: find the project's, and carry it to ${new}, the line that opens with '${label}', before ${old} is reconciled"
      fi
      continue
    fi
    fw show "${vx}:${old}" > "${d}/moved.vx" 2>/dev/null
    lf "${old}" > "${d}/moved.mine"
    ans="$(answer_at "${line}" "${d}/moved.vx" "${d}/moved.mine")"
    if [[ "${ans}" =~ ${MARKER_RE} ]]; then
      info "${old}: '$(short "${line}")' is open in the project, re-flowed: nothing to carry"
    else
      check "edge case 8: ${old}: the slot of '$(short "${line}")' is answered in the project${ans:+ ('$(clip "${ans}")')} — ${rel} moved it: carry the answer to ${new}${label:+, the line **${label}**}, before ${old} is reconciled"
    fi
  done < "${d}/moved"
  while IFS=$'\t' read -r rel old; do
    check "edge case 8: ${old}: ${rel} moved its slots, and ${vx}'s copy holds them in no form this check knows (a release before v1.1.0 wrote them in Italian): find them by the marker, and carry each answered one to CLAUDE.md's *The answers the method reads* by hand, before ${old} is reconciled"
  done < "${d}/moved.unknown"

  section "The §2 checklist of SETUP.md — items added or re-worded between ${vx} and ${vy}"
  local s2x="${d}/s2.x" s2y="${d}/s2.y"
  for r in "${vx}:${s2x}" "${vy}:${s2y}"; do
    # An item spans its continuation lines: they are joined, so a change on any of them
    # shows and a re-wrap does not.
    fw show "${r%%:*}:SETUP.md" 2>/dev/null | awk '/^## 2\./{f=1;next} /^## 3\./{f=0} f' | awk '
      /^- \[ \]/ { if (item != "") print item; item = $0; next }
      /^[ \t]+[^ \t]/ && item != "" { sub(/^[ \t]+/, ""); item = item " " $0; next }
      { if (item != "") print item; item = "" }
      END { if (item != "") print item }' | sort > "${r#*:}" || true
  done
  if [ ! -s "${s2y}" ]; then
    info "no §2 checklist in ${vy}'s SETUP.md"
  elif cmp -s "${s2x}" "${s2y}"; then
    ok "the §2 checklist is unchanged"
  elif [ -s "${s2x}" ] && [ -z "$(comm -12 "${s2x}" "${s2y}")" ]; then
    check "the whole §2 checklist is re-worded ($(wc -l < "${s2x}" | tr -d ' ') items in ${vx}, $(wc -l < "${s2y}" | tr -d ' ') in ${vy}; a translation?): read ${vy}'s in full against the project's answers"
  else
    comm -13 "${s2x}" "${s2y}" > "${d}/s2.added"
    comm -23 "${s2x}" "${s2y}" > "${d}/s2.removed"
    while IFS= read -r line; do check "§2, new or re-worded: ${line#- \[ \] }"; done < "${d}/s2.added"
    while IFS= read -r line; do info "§2, gone or re-worded: ${line#- \[ \] }"; done < "${d}/s2.removed"
  fi

  section "The memory's format — titles and field labels to rename (edge case 3 (b))"
  local f t pending=0 labels
  for f in .claude/memory/STATE.md .claude/memory/LEARNINGS.md; do
    [ -f "${f}" ] || { info "${f}: absent in the project"; continue; }
    while IFS= read -r t; do
      [ -n "${t}" ] || continue
      check "${f} lacks ${vy}'s title '${t}': rename the old one (the table of edge case 3 (b))"
      pending=$((pending + 1))
    done <<< "$(missing_titles "${vy}" "${f}")"
  done
  if [ -f .claude/memory/LEARNINGS.md ] && ! labels_renamed "${vy}"; then
    info "${vy}'s field labels are still the old form: none to rename"
  elif [ -f .claude/memory/LEARNINGS.md ]; then
    labels="$(old_labels .claude/memory/LEARNINGS.md)"
    [ "${labels}" -eq 0 ] || { check "${labels} line(s) of LEARNINGS.md carry an old-form field label: rename them (the table of edge case 3 (b))"; pending=$((pending + 1)); }
  fi
  [ "${pending}" -gt 0 ] || ok "titles and field labels already in ${vy}'s form"

  section "The Upgrading notes of the releases after ${vx}, oldest first — different topics add up; on the same topic the most recent wins (Step 2)"
  fw show "${vy}:CHANGELOG.md" > "${d}/changelog" 2>/dev/null || : > "${d}/changelog"
  for r in ${releases}; do
    awk -v h="## [${r#v}]" '
      index($0, h) == 1 { s = 1; next }
      s && /^## \[/ { exit }
      s && /^\*\*Upgrading/ { u = 1 }
      s && u { l[++n] = $0; if (NF) last = n }
      END { for (i = 1; i <= last; i++) print l[i] }' "${d}/changelog" > "${d}/note"
    if [ -s "${d}/note" ]; then
      info "${r}:"
      sed 's/^/       | /' "${d}/note"
    else
      info "${r}: no Upgrading paragraph — read its entry in ${vy}'s CHANGELOG"
    fi
  done
  finish "inventory ${vx} -> ${vy}"
}

# format_done <vY>: after the rename, no title of vY missing and no old-form label (FAIL).
format_done() {
  local vy="$1" f t pending=0
  section "The memory's format — titles and field labels (edge case 3 (b))"
  for f in .claude/memory/STATE.md .claude/memory/LEARNINGS.md; do
    [ -f "${f}" ] || continue
    while IFS= read -r t; do
      [ -n "${t}" ] || continue
      fail "${f} still lacks ${vy}'s title '${t}': the rename is mandatory"
      pending=$((pending + 1))
    done <<< "$(missing_titles "${vy}" "${f}")"
  done
  if [ -f .claude/memory/LEARNINGS.md ] && labels_renamed "${vy}" && [ "$(old_labels .claude/memory/LEARNINGS.md)" -gt 0 ]; then
    fail "$(old_labels .claude/memory/LEARNINGS.md) line(s) of LEARNINGS.md still carry an old-form field label: the rename is mandatory"
    pending=$((pending + 1))
  fi
  [ "${pending}" -gt 0 ] || ok "titles and field labels in ${vy}'s form"
}

# --- invariant -------------------------------------------------------------------------

# pointer_repairs_only <before> <after>: prints nothing when every change between the two
# files is a pointer repair (edge case 3 (a)) — each hunk removes as many lines as it adds,
# and each removed line equals its added one once its pointers are masked ([[wikilinks]],
# paths ending in .md, docs/…). Otherwise it prints the first line that breaks the rule.
pointer_repairs_only() {
  diff -U0 "$1" "$2" | awk '
    function mask(l) {
      gsub(/\[\[[^]]*\]\]/, "[[@]]", l)
      gsub(/[A-Za-z0-9_.\/#:-]*\.md[A-Za-z0-9_.\/#:-]*/, "@md", l)
      gsub(/docs\/[A-Za-z0-9_.\/#:-]*/, "@docs", l)
      return l
    }
    # The finding carries its sign, so that an emptied line is still a finding.
    function close_hunk(   i) {
      if (nr != na) { if (bad == "") bad = (nr > na ? "-" rem[1] : "+" add[1]) }
      else for (i = 1; i <= nr; i++) if (bad == "" && mask(rem[i]) != mask(add[i])) bad = "-" rem[i] " => +" add[i]
      nr = 0; na = 0
    }
    NR <= 2 { next }
    /^@@/ { close_hunk(); next }
    /^-/ { rem[++nr] = substr($0, 2); next }
    /^\+/ { add[++na] = substr($0, 2); next }
    END { close_hunk(); if (bad != "") print bad }'
}

# body_region <file>: from the first "## " heading to the end (LEARNINGS.md's memory part).
body_region() { awk '/^## /{b=1} b' "$1"; }
# comments_of <file>: its comment blocks, each closed by a line "@@END".
comments_of() { awk '/^<!--/{c=1} c{print} /-->[[:space:]]*$/{if (c) print "@@END"; c=0}' "$1"; }
# without_comments <file>: the file without its comment blocks.
without_comments() { awk '/^<!--/{c=1} !c{print} /-->[[:space:]]*$/{c=0}' "$1"; }
# show_diff <a> <b>: the first lines of a unified diff, indented, for a human to read.
show_diff() { diff -u "$1" "$2" | sed -n '3,40p' | sed 's/^/       | /'; }

cmd_invariant() {
  [ $# -eq 3 ] || die "usage: invariant vX vY <restore point: the project's pre-upgrade commit>"
  local vx="$1" vy="$2" restore="$3"
  require_fw
  require_project_root
  require_tag "${vx}"
  require_tag "${vy}"
  require_t
  pg rev-parse -q --verify "${restore}^{commit}" >/dev/null || die "the restore point ${restore} is not a commit of the project"
  local d="${WORK}/invariant"
  rm -rf "${d}" && mkdir -p "${d}" || die "cannot prepare ${d}"

  # A wrong restore point makes every check below pass on nothing: it is checked first.
  section "The restore point ${restore}"
  local restore_pin
  if pg merge-base --is-ancestor "${restore}" HEAD; then
    ok "${restore} is an ancestor of HEAD"
  else
    fail "${restore} is not an ancestor of HEAD: the restore point is the commit the upgrade branch started from (Step 1)"
  fi
  if pg diff --quiet "${restore}" -- "${PAYLOAD_PATHS[@]}" \
    && [ -z "$(pg ls-files --others --exclude-standard -- "${PAYLOAD_PATHS[@]}")" ]; then
    fail "nothing in the payload changed since ${restore}: it is not the commit before the upgrade (Step 1)"
  fi
  restore_pin="$(pg show "${restore}:.claude/framework-version" 2>/dev/null \
    | awk 'index($0, "version:") == 1 { v = substr($0, 9); sub(/#.*/, "", v); gsub(/\r/, "", v); gsub(/^[ \t]+|[ \t]+$/, "", v); print v; exit }')"
  [ -z "${restore_pin}" ] || [ "${restore_pin}" = "${vx}" ] \
    || check "the restore point's pin reads '${restore_pin}', not ${vx}: is it the commit before the upgrade?"

  section "The touches on .claude/memory/ since ${restore} — a closed list (SETUP.md, Step 5, before the checkpoint)"
  { pg diff --no-ext-diff --name-status --no-renames "${restore}" -- .claude/memory
    pg ls-files --others --exclude-standard -- .claude/memory | awk '{ print "A\t" $0 }'
  } > "${d}/changes"
  [ -s "${d}/changes" ] || ok "no change under .claude/memory/"
  local st path class bad mnow mrest added
  while IFS=$'\t' read -r st path; do
    [ -n "${path}" ] || continue
    class="$(classify "${path}")"
    if [ "${st}" = D ]; then
      fail "${path} is deleted: an upgrade removes nothing from the memory"
      continue
    fi
    case "${class}" in
      TEMPLATE)
        if [ "$(pg hash-object -- "${path}")" = "$(blob_at "${vy}" "${path}")" ]; then
          ok "${path}: the memory template at ${vy}"
        else
          check "${path}: a memory template that differs from ${vy}'s — fine only for the project's own customisation, kept through the 3-way:"
          fw show "${vy}:${path}" > "${d}/template"
          lf "${path}" > "${d}/template.now"
          show_diff "${d}/template" "${d}/template.now"
        fi
        # A slot answered at the restore point must not be open again: no more markers
        # than vY itself added (none, when vY removed or moved one).
        mnow="$(file_markers "${path}")"
        mrest="$(pg show "${restore}:${path}" 2>/dev/null | grep -oE "${MARKER_RE}" | wc -l | tr -d ' ')"
        added="$(markers_added "${vx}" "${path}" "${vy}" "${path}")"
        [ $((mnow - mrest)) -le "${added}" ] \
          || fail "${path}: a slot the project had answered is open again — re-apply its answer" ;;
      LEARNINGS)
        info "${path}: see its own section below" ;;
      PROJECT-MEMORY)
        case "${st}:${path}" in
          A:.claude/memory/sessions/* | A:.claude/memory/plans/*)
            ok "${path}: added — the upgrade's own session note or plan" ;;
          A:.claude/memory/decisions/*)
            ok "${path}: added — the upgrade's own decision record (docs/01: structural choices are recorded before the plan)" ;;
          A:*)
            fail "${path}: added outside the upgrade's own note, plan and decision records" ;;
          *)
            # STATE, TREE, INDEX and every note: only the pointer repairs of edge case 3 (a)
            # and the titles and labels renamed by (b). Before the checkpoint, that is all.
            pg show "${restore}:${path}" > "${d}/before.raw" 2>/dev/null
            normalise_format "${d}/before.raw" > "${d}/before"
            lf "${path}" | normalise_format /dev/stdin > "${d}/after"
            bad="$(pointer_repairs_only "${d}/before" "${d}/after")"
            if [ -z "${bad}" ]; then
              ok "${path}: unchanged but for pointer repairs (edge case 3 (a)) and renamed titles or labels"
            else
              fail "${path}: changed beyond pointer repairs and the format's rename — at Step 5 the checkpoint has not run yet: ${bad}"
            fi ;;
        esac ;;
      *)
        fail "${path}: ${class} — not a file an upgrade touches under .claude/memory/" ;;
    esac
  done < "${d}/changes"

  section "LEARNINGS.md — the header is a template; the IMP entries are the project's memory"
  local f=.claude/memory/LEARNINGS.md
  if [ ! -f "${f}" ]; then
    info "${f}: absent"
  else
    lf "${f}" | header_region /dev/stdin > "${d}/h.now"
    fw show "${vy}:${f}" > "${d}/vy.learnings"
    header_region "${d}/vy.learnings" > "${d}/h.vy"
    if cmp -s "${d}/h.now" "${d}/h.vy"; then
      ok "the header is ${vy}'s"
    else
      check "the header differs from ${vy}'s — fine only for the project's own text, kept through the 3-way:"
      show_diff "${d}/h.vy" "${d}/h.now"
    fi
    lf "${f}" | body_region /dev/stdin > "${d}/b.now"
    body_region "${d}/vy.learnings" > "${d}/b.vy"
    pg show "${restore}:${f}" 2>/dev/null | body_region /dev/stdin > "${d}/b.before"
    comments_of "${d}/b.now" > "${d}/c.now"
    comments_of "${d}/b.vy" > "${d}/c.vy"
    local cnow cvy
    cnow="$(grep -c '^@@END$' "${d}/c.now")"; cvy="$(grep -c '^@@END$' "${d}/c.vy")"
    if [ "${cnow}" -gt "${cvy}" ]; then
      fail "the body has ${cnow} comment block(s), ${vy}'s format has ${cvy}: an extra block can hide an IMP entry — a project grafted before v1.1.0 still has a second, obsolete format comment (the Applied one): remove it (Step 3)"
    elif [ "${cnow}" -lt "${cvy}" ]; then
      check "the body has ${cnow} comment block(s), ${vy}'s format has ${cvy}: bring ${vy}'s format comment over (Step 3), or confirm the project dropped it"
    elif cmp -s "${d}/c.now" "${d}/c.vy"; then
      ok "the format comment is ${vy}'s"
    else
      check "the format comment differs from ${vy}'s — a project's rewording, or an entry hidden inside it:"
      show_diff "${d}/c.vy" "${d}/c.now"
    fi
    # Blank lines carry no content, and replacing a format comment moves them: they are
    # left out of the comparison, as the old-form titles and labels are normalised.
    # The section titles become one placeholder: format_done checks them against vY's,
    # and a project's own shortened title, renamed, is not an entry's change. An entry
    # moved across sections still shows: the order of lines and placeholders counts.
    without_comments "${d}/b.before" > "${d}/e.before.raw"
    normalise_format "${d}/e.before.raw" | awk 'NF { if (/^## /) print "## <section>"; else print }' > "${d}/e.before"
    without_comments "${d}/b.now" > "${d}/e.now.raw"
    normalise_format "${d}/e.now.raw" | awk 'NF { if (/^## /) print "## <section>"; else print }' > "${d}/e.now"
    if cmp -s "${d}/e.before" "${d}/e.now"; then
      ok "the IMP entries are unchanged (titles and field labels compared in their new form, blank lines aside)"
    else
      fail "the IMP entries changed — an upgrade never edits them (run this at Step 5, before the checkpoint: its retro may add entries):"
      show_diff "${d}/e.before" "${d}/e.now"
    fi
  fi

  format_done "${vy}"

  # An answer the restore point held, in a file a release in between moved it out of, has
  # a line in its new home, the line no longer holds the setup marker, and it holds the
  # answer the restore point held, word for word — or a human confirms it (edge case 8): two
  # answers can share a label, and a line closed by one says nothing of the other.
  section "Answers a release in between moved — each in its new home (edge case 8)"
  local rel old line new label default ans home elsewhere
  moved_here "${vx}" "${vy}" "${d}/moved"
  [ -s "${d}/moved" ] || [ -s "${d}/moved.unknown" ] || ok "no release between ${vx} and ${vy} moved a slot"
  while IFS=$'\t' read -r rel old line new label default; do
    if ! pg show "${restore}:${old}" 2>/dev/null | tr -d '\r' > "${d}/moved.before" || [ ! -s "${d}/moved.before" ]; then
      ok "${old}: absent at the restore point, nothing to carry"
      continue
    fi
    if slot_open "${line}" "${d}/moved.before"; then
      elsewhere=""
      if [ -n "${default}" ]; then
        pg show "${restore}:${new}" 2>/dev/null > "${d}/moved.new.before" || : > "${d}/moved.new.before"
        elsewhere="$(value_elsewhere "${line}" "${new}" "${vx}" "${d}/moved.new.before" "${d}/elsewhere" | head -n 1)"
      fi
      if [ -n "${elsewhere}" ]; then
        home="$(home_value "${label}" "${new}" || true)"
        check "${old}: '$(short "${line}")' was open at the restore point, but its ${new} set the variable on a line of its own ('$(clip "$(short "${elsewhere}")")'): confirm the value is on ${new}'s line '${label}' ('$(clip "${home}")') (edge case 8)"
      else
        ok "${old}: '$(short "${line}")' was open at the restore point, nothing to carry"
      fi
      continue
    fi
    # A value slot: the value the restore point held, against the new home's line, on the
    # value itself — the default left there is the answer lost.
    if [ -n "${default}" ]; then
      ans="$(value_at "${line}" "${default}" "${d}/moved.before")"
      if ! home="$(home_value "${label}" "${new}")"; then
        fail "${new} has no line that opens with '${label}': the value of ${old}'s '$(short "${line}")' has no home — bring ${vy}'s line over"
      elif [ -z "${ans}" ]; then
        check "${old}: '$(short "${line}")' had another form at the restore point: confirm the project's value is on ${new}'s line '${label}' ('$(clip "${home}")') (edge case 8)"
      elif [ "${home}" = "${ans}" ]; then
        ok "${old}: its value ('$(clip "${ans}")') is on ${new}'s line '${label}'"
      elif [ "${home}" = "${default}" ]; then
        fail "${old}: the restore point held '$(clip "${ans}")', and ${new}'s line '${label}' still holds the default '${default}': carry the value there (edge case 8)"
      else
        check "${old}: the restore point held '$(clip "${ans}")', and ${new}'s line '${label}' holds '$(clip "${home}")': confirm the value is carried (edge case 8)"
      fi
      continue
    fi
    fw show "${vx}:${old}" > "${d}/moved.vx" 2>/dev/null
    ans="$(answer_at "${line}" "${d}/moved.vx" "${d}/moved.before")"
    if [[ "${ans}" =~ ${MARKER_RE} ]]; then
      ok "${old}: '$(short "${line}")' was open at the restore point, re-flowed, nothing to carry"
    elif [ -z "${label}" ]; then
      check "${old}: '$(short "${line}")' was answered at the restore point${ans:+ ('$(clip "${ans}")')}: its answer belongs in ${new} (${rel}) — confirm it is there"
    else
      # The label's line and the lines it runs on to.
      lf "${new}" 2>/dev/null | awk -v p="- **${label}**" 'index($0, p) == 1 { f = 1; print; next } f && /^[ \t]+[^ \t]/ { print; next } { f = 0 }' > "${d}/moved.home"
      if [ ! -s "${d}/moved.home" ]; then
        fail "${new} has no line **${label}**: the answer of ${old}'s '$(short "${line}")' has no home — bring ${vy}'s line over"
      elif grep -E "${MARKER_RE}" "${d}/moved.home" >/dev/null; then
        fail "${old}: '$(short "${line}")' was answered at the restore point, and its new line in ${new}, **${label}**, is still open: carry the answer there (edge case 8)"
      # Searched past vY's own text before the marker: the line's description names options
      # — "via Pull Request or via the `/fw:integrate` block" — an answer would match unwritten.
      # And as a whole word or phrase: no letter, digit or underscore glued to an end of it that
      # is one — "main" is not on a line that says "mainline"; ASCII's letters only, so an
      # answer glued to an accented one still matches, and a miss is a CHECK, never a FAIL.
      # A known limit: a description
      # the project re-worded is searched whole, so an answer it names still matches; Step 4's
      # marker grep and the human's reading remain.
      elif [ -n "${ans}" ] && A="${ans}" V="$(fw show "${vy}:${new}" 2>/dev/null | tr -d '\r' | awk -v p="- **${label}**" 'index($0, p) == 1 && !f { f = 1; print }')" awk "${SLOT_NORM}"'
          function isword(c) { return c ~ /^[A-Za-z0-9_]$/ }
          function holds(h, a,    j, i, p, b, e) {
            for (j = 0; (i = index(substr(h, j + 1), a)) > 0; j += i) {
              p = j + i; b = p > 1 ? substr(h, p - 1, 1) : ""; e = substr(h, p + length(a), 1)
              if (!(isword(substr(a, 1, 1)) && isword(b)) && !(isword(substr(a, length(a), 1)) && isword(e))) return 1
            }
            return 0
          }
          { h = h " " $0 }
          END {
            h = norm(h); v = ENVIRON["V"]; i = index(v, "[TO BE DEFINED AT SETUP]")
            if (i > 0) { v = norm(substr(v, 1, i - 1)); if (v != "" && index(h, v) == 1) h = substr(h, length(v) + 1) }
            exit !holds(h, ENVIRON["A"])
          }' "${d}/moved.home"; then
        ok "${old}: its answer ('$(clip "${ans}")') is on ${new}'s line **${label}**"
      else
        check "${old}: '$(short "${line}")' was answered at the restore point${ans:+ with '$(clip "${ans}")'}, which ${new}'s line **${label}** does not hold word for word: confirm the answer is carried there (edge case 8)"
      fi
    fi
  done < "${d}/moved"
  while IFS=$'\t' read -r rel old; do
    check "${old}: ${rel} moved its slots, and ${vx}'s copy holds them in no form this check knows (a release before v1.1.0 wrote them in Italian): confirm by hand that each answer the restore point held there is on its line of CLAUDE.md's *The answers the method reads*"
  done < "${d}/moved.unknown"

  # A value a hybrid holds in place, where no release in between moved it (IMP-130): a release
  # that changes the line next to it puts the value in the 3-way's conflict — v4.1.0's comment
  # on YES, above the Makefile's protected branches, the rehearsal's own case —, and taking
  # vY's side there brings vY's default back with no marker to show it. The restore point's
  # value against the line now: vY's default where the project held its own is a FAIL.
  section "Values a hybrid holds in place — each still the project's"
  local vfile vlabel was now dflt other
  while IFS=$'\t' read -r vfile vlabel; do
    # Moved in between: edge case 8's, above — said, so the section is never an empty heading.
    if awk -F'\t' -v f="${vfile}" -v l="${vlabel}" '$4 == f && $5 == l { m = 1 } END { exit !m }' "${d}/moved"; then
      info "${vfile}: '${vlabel}' moved in between — its value checked above (edge case 8)"
      continue
    fi
    pg show "${restore}:${vfile}" 2>/dev/null | tr -d '\r' > "${d}/value.before" || : > "${d}/value.before"
    if ! was="$(home_value "${vlabel}" "${d}/value.before")"; then
      # No line in vY's form at the restore point: another form of the assignment — no space,
      # `:=`, `?=`, a recipe's — that vX's own copy does not hold is a value of the project's
      # all the same, which vY's side would lose: a CHECK, never silence on a line not found
      # (the gate's round 2, 2026-10-18).
      fw show "${vx}:${vfile}" 2>/dev/null | tr -d '\r' > "${d}/value.vx" || : > "${d}/value.vx"
      awk -v v="${vlabel%% *}" '$0 ~ "^[[:space:]]*" v "[[:space:]]*[:?+!]?=" { print }' "${d}/value.before" > "${d}/value.sets"
      other="$(grep -vxFf "${d}/value.vx" "${d}/value.sets" | head -n 1 || true)"
      if [ -n "${other}" ]; then
        check "${vfile}: the restore point sets ${vlabel%% *} in another form ('$(clip "${other}")'), not on a line '${vlabel}': confirm the project's value is on that line now"
      else
        info "${vfile}: no line '${vlabel}' at the restore point, no value of the project's to keep"
      fi
      continue
    fi
    fw show "${vy}:${vfile}" 2>/dev/null | tr -d '\r' > "${d}/value.vy" || : > "${d}/value.vy"
    if ! dflt="$(home_value "${vlabel}" "${d}/value.vy")"; then
      check "${vfile}: ${vy} has no line '${vlabel}': confirm where the project's value ('$(clip "${was}")') went"
    elif ! now="$(home_value "${vlabel}" "${vfile}")"; then
      fail "${vfile} has no line that opens with '${vlabel}': the restore point held '$(clip "${was}")' there — bring ${vy}'s line over with the project's value"
    elif [ "${now}" = "${was}" ]; then
      ok "${vfile}: its value ('$(clip "${was}")') is still on its line '${vlabel}'"
    elif [ "${now}" = "${dflt}" ]; then
      fail "${vfile}: the restore point held '$(clip "${was}")' on its line '${vlabel}', which now holds ${vy}'s default '$(clip "${dflt}")': the resolution took vY's side there — carry the project's value back"
    else
      check "${vfile}: the restore point held '$(clip "${was}")' on its line '${vlabel}', which now holds '$(clip "${now}")': confirm the value is the project's"
    fi
  done < <(value_slots)
  finish "invariant ${vx} -> ${vy}, since ${restore}"
}

# --- post --------------------------------------------------------------------------------

cmd_post() {
  [ $# -eq 2 ] || die "usage: post vX vY"
  local vx="$1" vy="$2"
  require_fw
  require_project_root
  require_tag "${vx}"
  require_tag "${vy}"
  require_t
  local d="${WORK}/post" path class by bx bp n_at=0 modey modep
  rm -rf "${d}" && mkdir -p "${d}" || die "cannot prepare ${d}"
  moved_here "${vx}" "${vy}" "${d}/moved"

  section "The payload against ${vy} — METHOD files at ${vy}, every file present, modes"
  awk -F'\t' '{print $2}' "$(tree_of "${vy}")" > "${d}/paths.vy"
  while IFS= read -r path; do
    class="$(classify "${path}")"
    case "${class}" in PROJECT-MEMORY | LOCAL | GRAFT-STATE | LEARNINGS) continue ;; esac
    if [ ! -f "${path}" ]; then
      fail "${path} (${class}) is missing: bring it over from ${vy}"
      continue
    fi
    by="$(blob_at "${vy}" "${path}")"
    bx="$(blob_at "${vx}" "${path}")"
    bp="$(pg hash-object -- "${path}")"
    if [ -n "${bx}" ] && [ "${bx}" != "${by}" ] && [ "${bp}" = "${bx}" ]; then
      fail "${path} (${class}) is still ${vx}'s: Step 3 has not brought ${vy}'s over"
      continue
    fi
    # The conflict markers a 3-way leaves behind.
    if grep -nE '^(<<<<<<<|>>>>>>>|\|\|\|\|\|\|\|) ' "${path}" > "${d}/conflicts" 2>/dev/null; then
      fail "${path}: conflict markers left by a merge, first at line $(head -n 1 "${d}/conflicts" | cut -d: -f1)"
    fi
    case "${class}" in
      METHOD)
        if [ "${bp}" = "${by}" ]; then
          n_at=$((n_at + 1))
        elif in_list "${d}/moved" "${path}" || in_list "${d}/moved.unknown" "${path}"; then
          check "${path} (METHOD) differs from ${vy}'s: its answers moved to another file (edge case 8) — bring it over once they are there; any other difference is edge case 7's"
        else
          check "${path} (METHOD) differs from ${vy}'s: fine only if it was reconciled as a hybrid (edge case 7)"
        fi ;;
      TEMPLATE)
        [ "${bp}" = "${by}" ] && n_at=$((n_at + 1)) \
          || check "${path} (TEMPLATE) differs from ${vy}'s: fine only for the project's own customisation" ;;
      NONE) fail "no class for ${path}" ;;
    esac
    modey="$(mode_at "${vy}" "${path}")"
    modep="$(mode_of "${path}")"
    [ "${modey}" = "${modep}" ] || fail "${path}: mode ${modep}, ${vy}'s is ${modey} (chmod, on Windows git update-index --chmod: Step 3)"
  done < "${d}/paths.vy"
  ok "${n_at} METHOD and TEMPLATE files identical to ${vy}'s"
  if grep -nE '^(<<<<<<<|>>>>>>>|\|\|\|\|\|\|\|) ' .claude/memory/LEARNINGS.md > "${d}/conflicts" 2>/dev/null; then
    fail ".claude/memory/LEARNINGS.md: conflict markers left by the header's merge, first at line $(head -n 1 "${d}/conflicts" | cut -d: -f1)"
  fi
  # Orphans: what vY removed must be gone from the project too — a renamed file's old copy
  # included, which would sit beside the new one (edge case 2).
  awk -F'\t' '{print $2}' "$(tree_of "${vx}")" | sort > "${d}/paths.vx.sorted"
  sort "${d}/paths.vy" > "${d}/paths.vy.sorted"
  comm -23 "${d}/paths.vx.sorted" "${d}/paths.vy.sorted" | while IFS= read -r path; do
    case "$(classify "${path}")" in PROJECT-MEMORY | LOCAL | GRAFT-STATE) continue ;; esac
    [ -e "${path}" ] && echo "${path}"
  done > "${d}/orphans"
  renames_between "${vx}" "${vy}" > "${d}/renames"
  local new
  if [ -s "${d}/orphans" ]; then
    while IFS= read -r path; do
      new="$(renamed_to "${d}/renames" "${path}")"
      if [ -z "${new}" ]; then
        fail "${path} is an orphan: ${vy} removed it (edge case 1)"
      else
        case "${path}" in
          # A command file left at its old place still runs under its bare name, and a bare
          # name can be one of Claude Code's own commands, which it then hides.
          .claude/commands/*) fail "${path} is the old place of ${new} (edge case 2): remove it once merged — until then Claude Code runs it under its bare name, and a bare name can hide one of its own commands" ;;
          *) fail "${path} is the old place of ${new} (edge case 2): remove it once merged" ;;
        esac
      fi
    done < "${d}/orphans"
  else
    ok "no orphan of a file ${vy} removed or renamed"
  fi

  section "Slots — markers broken by a wrap, and the slots ${vy} added"
  local na from
  while IFS= read -r path; do
    case "$(classify "${path}")" in METHOD | HYBRID | TEMPLATE) ;; *) continue ;; esac
    [ -f "${path}" ] || continue
    # Read from a file, not a pipe: a loop on a pipe runs in a subshell, and its FAILs
    # would not be counted.
    grep -nE "${BROKEN_MARKER_RE}" "${path}" > "${d}/broken" || true
    while IFS= read -r line; do
      fail "${path}:${line} — a marker broken by a line wrap: keep it on one line"
    done < "${d}/broken"
    from="$(renamed_from "${d}/renames" "${path}")"
    na="$(markers_added "${vx}" "${from:-${path}}" "${vy}" "${path}")"
    if [ "${na}" -gt 0 ]; then
      check "${vy} added ${na} slot(s) to ${path}: confirm the project's answer is in place, not the framework's default:"
      lf "${path}" | grep -nE -A1 "${MARKER_RE}" | sed 's/^/       | /'
    fi
  done < "${d}/paths.vy"

  section "Hooks — every hook of the project's scripts/hooks-install.sh is installed (Step 4)"
  local hooks h n_h=0
  hooks="$(git rev-parse --path-format=absolute --git-common-dir)/hooks"
  for h in $(lf scripts/hooks-install.sh 2>/dev/null | sed -n 's/^for hook in \(.*\); do$/\1/p'); do
    n_h=$((n_h + 1))
    if grep -qF "${HOOK_MARKER}" "${hooks}/${h}" 2>/dev/null; then
      ok "${h} installed, with the generator's marker"
    else
      fail "${h} missing or foreign in ${hooks}: run make hooks-install"
    fi
  done
  [ "${n_h}" -gt 0 ] || fail "no hook list found in scripts/hooks-install.sh"

  format_done "${vy}"

  section "The provenance pin"
  local version
  version="$( [ -f .claude/framework-version ] && pin_field version )"
  if [ "${version}" = "${vy}" ]; then
    ok "the pin reads ${vy}"
  elif [ "${version}" = "${vx}" ] || [ -z "${version}" ]; then
    check "the pin reads '${version:-nothing}': Step 6 writes 'version: ${vy}' and its commit"
  else
    fail "the pin reads '${version}', neither ${vx} nor ${vy}"
  fi
  finish "post ${vx} -> ${vy}"
}

main() {
  [ $# -ge 1 ] || die "usage: upgrade-check.sh classes|preflight|inventory|invariant|post ..."
  local sub="$1"
  shift
  case "${sub}" in
    classes) cmd_classes "$@" ;;
    preflight) cmd_preflight "$@" ;;
    inventory) cmd_inventory "$@" ;;
    invariant) cmd_invariant "$@" ;;
    post) cmd_post "$@" ;;
    *) die "unknown subcommand: ${sub}" ;;
  esac
}

main "$@"
