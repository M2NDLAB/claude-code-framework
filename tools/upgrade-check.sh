#!/usr/bin/env bash
# tools/upgrade-check.sh — the read-only checks of a framework upgrade (vX -> vY).
#
# Why it exists: an upgrade mixes judgement (how to resolve a conflict, which
# customisation to keep) with mechanics that are the same every time — which files
# changed and how much they collide with the project's, which slots moved, whether the
# project's memory was touched only where allowed. Three real upgrades rebuilt those
# mechanics by hand or with throwaway scripts. This script holds them; SETUP.md,
# *Upgrading the framework*, stays the procedure and calls it at fixed points.
#
# What it promises:
#   - it READS the framework only by tag (git -C "$FW" show|ls-tree|rev-parse <tag>),
#     never its working tree, and the project read-only (git --no-optional-locks);
#   - it WRITES only under "$T/upgrade-check/";
#   - it DECIDES nothing: every finding is a line OK, FAIL (a rule of the procedure is
#     broken) or CHECK (a human must look); the exit code is 1 when any line is FAIL,
#     2 on a usage or environment error, 0 otherwise.
#
# It lives in the framework repository, OUTSIDE the payload setup copies. An upgrade
# runs the copy AT THE TAG vY — never one kept in the project, never the framework's
# working tree — from the PROJECT's root, with the procedure's FW and T:
#   git -C "${FW:?}" show vY:tools/upgrade-check.sh > "${T:?}/upgrade-check.sh"
#   FW="$FW" T="$T" bash "${T:?}/upgrade-check.sh" <subcommand> ...
# Subcommands:
#   classes <rev>              the class of every payload file at <rev> (needs FW only)
#   preflight vX vY            the Precondition and the provenance pin
#   inventory vX vY            the per-file triage and measurement, the edge-case flags,
#                              the markers, the §2 checklist, titles and labels, and the
#                              Upgrading notes of the releases in between
#   invariant vX vY <restore>  the closed list of allowed touches on .claude/memory/,
#                              against the restore point (the pre-upgrade commit)
#   post vX vY                 METHOD files and modes at vY, orphans, markers, hooks
#
# Compatible with bash 3.2 (macOS's /bin/bash): no associative arrays, no mapfile.
set -u -o pipefail

# What setup copies into a project (SETUP.md, step 1): the payload.
readonly PAYLOAD_PATHS=(.claude CLAUDE.md Makefile commitlint.config.cjs .gitignore scripts)
# The slot marker, in both forms: a project grafted before v1.1.0 carries the Italian one.
readonly MARKER_RE='TO BE DEFINED AT SETUP|DA DEFINIRE AL SETUP'
# A marker broken by a line wrap: what is left at the end of the line.
readonly BROKEN_MARKER_RE='\[(TO|TO BE|TO BE DEFINED|TO BE DEFINED AT)[[:space:]]*$|\[(DA|DA DEFINIRE|DA DEFINIRE AL)[[:space:]]*$'
readonly HOOK_MARKER='Hook generated by scripts/hooks-install.sh'

n_fail=0
n_check=0
ok()      { printf 'OK     %s\n' "$*"; }
fail()    { printf 'FAIL   %s\n' "$*"; n_fail=$((n_fail + 1)); }
check()   { printf 'CHECK  %s\n' "$*"; n_check=$((n_check + 1)); }
info()    { printf 'INFO   %s\n' "$*"; }
section() { printf '\n== %s\n' "$*"; }
die()     { printf 'upgrade-check: %s\n' "$*" >&2; exit 2; }
# The last line of every subcommand, and its exit code.
finish() {
  printf '\n%s: %d FAIL, %d CHECK\n' "$1" "${n_fail}" "${n_check}"
  [ "${n_fail}" -eq 0 ] && exit 0
  exit 1
}

# Framework side: always by -C, so nothing ever resolves in the project.
fw() { git -C "${FW}" "$@"; }

# classify <path>: the class of a payload file, named one by one outside the memory, so
# that a file added to the payload has NO class until someone decides it (the self-test
# fails on it). The classes are those of SETUP.md, *The mental model*:
#   METHOD          pure framework, brought to vY as it is
#   HYBRID          a framework part and a project part, reconciled 3-way
#   TEMPLATE        a memory template: a guide README, reconciled 3-way
#   LEARNINGS       its header region is a template, its body the project's memory
#   PROJECT-MEMORY  the project's own memory, never reconciled (STATE, TREE, INDEX too)
#   GRAFT-STATE     the provenance pin, rewritten at the close of the upgrade
#   LOCAL           not versioned, never touched
classify() {
  case "$1" in
    .claude/memory/components/README.md | .claude/memory/decisions/README.md | \
    .claude/memory/plans/README.md | .claude/memory/sessions/README.md)
      echo TEMPLATE ;;
    .claude/memory/LEARNINGS.md) echo LEARNINGS ;;
    .claude/memory/*) echo PROJECT-MEMORY ;;
    .claude/framework-version) echo GRAFT-STATE ;;
    .claude/settings.local.json | .claude/worktrees/*) echo LOCAL ;;
    CLAUDE.md | .claude/settings.json | .gitignore | Makefile | scripts/hooks-install.sh | \
    .claude/commands/checkpoint.md | .claude/commands/integrate.md | \
    .claude/commands/new-component.md)
      echo HYBRID ;;
    .claude/docs/00-overview.md | .claude/docs/01-task-planning.md | \
    .claude/docs/02-code-quality.md | .claude/docs/03-security-gate.md | \
    .claude/docs/04-git-workflow.md | .claude/docs/05-escalation-protocol.md | \
    .claude/docs/06-self-improvement.md | \
    .claude/commands/harvest-framework.md | .claude/commands/lint-memory.md | \
    .claude/commands/retro.md | .claude/commands/security-review.md | \
    .claude/commands/sos.md | \
    scripts/README.md | scripts/reset-task.sh | scripts/agent-git-guard.mjs | \
    scripts/repo-snapshot.sh | scripts/test-hooks-install.sh | \
    scripts/test-agent-git-guard.sh | scripts/test-repo-snapshot.sh | \
    commitlint.config.cjs)
      echo METHOD ;;
    *) echo NONE ;;
  esac
}

require_fw() {
  [ -n "${FW:-}" ] || die "FW is not set: the absolute path of the framework's clone (SETUP.md, Precondition)"
  local prefix
  prefix="$(git -C "${FW}" rev-parse --show-prefix 2>/dev/null)" || die "FW=${FW} is not a git repository"
  [ -z "${prefix}" ] || die "FW=${FW} is not the root of its repository"
}

require_rev() {
  fw rev-parse -q --verify "$1^{commit}" >/dev/null || die "$1 not found in FW=${FW}"
}

# A tag, not any revision: the framework is read only by tag.
require_tag() {
  fw rev-parse -q --verify "refs/tags/$1^{commit}" >/dev/null \
    || die "tag $1 not found in FW=${FW} (fetching the tags is a human step: git -C \"\$FW\" fetch --tags)"
}

require_t() {
  [ -n "${T:-}" ] || die "T is not set: a scratch directory outside both repositories (SETUP.md, Precondition)"
  [ -d "${T}" ] || die "T=${T} does not exist: create it first (mkdir -p)"
  WORK="${T}/upgrade-check"
  mkdir -p "${WORK}" || die "cannot create ${WORK}"
}

# The project's root, git 2.31 or later, and a FW that is not the project itself.
require_project_root() {
  local top common_project common_fw
  top="$(git rev-parse --show-toplevel 2>/dev/null)" || die "not inside a git repository: run it from the project's root"
  [ "${top}" = "$(pwd -P)" ] || die "run it from the project's root (${top}), not from $(pwd -P)"
  common_project="$(git rev-parse --path-format=absolute --git-common-dir 2>/dev/null)"
  case "${common_project}" in
    /*) ;;
    *) die "git 2.31 or later is required (rev-parse --path-format)" ;;
  esac
  common_fw="$(fw rev-parse --path-format=absolute --git-common-dir)"
  [ "${common_project}" != "${common_fw}" ] || die "FW is the project itself: FW must be the framework's clone"
}

# payload_files <rev>: the payload at a revision of the framework, one path per line.
payload_files() {
  fw ls-tree -r --name-only "$1" -- "${PAYLOAD_PATHS[@]}"
}

cmd_classes() {
  [ $# -eq 1 ] || die "usage: classes <rev>"
  require_fw
  require_rev "$1"
  local path class n=0 none=0
  while IFS= read -r path; do
    class="$(classify "${path}")"
    printf '%-15s %s\n' "${class}" "${path}"
    n=$((n + 1))
    if [ "${class}" = NONE ]; then
      none=$((none + 1))
      fail "no class for ${path}: name it in classify() of tools/upgrade-check.sh, and in SETUP.md's classes"
    fi
  done < <(payload_files "$1")
  [ "${n}" -gt 0 ] || fail "no payload file at $1: the payload paths are wrong"
  finish "classes ($n files, $none without a class)"
}

# pin_field <name>: the value of the pin's `name: value` line, without a trailing comment
# or blanks (the example of SETUP.md carries `# …` comments); empty when the line is
# missing. The pin is .claude/framework-version, read from the project's root.
pin_field() {
  awk -v k="$1" 'index($0, k ":") == 1 {
      v = substr($0, length(k) + 2); sub(/#.*/, "", v); gsub(/^[ \t]+|[ \t]+$/, "", v)
      print v; exit
    }' .claude/framework-version
}

# tags_on <object>: the framework's v* tags on the commit an object names, space-separated.
tags_on() {
  local commit
  commit="$(fw rev-parse -q --verify "$1^{commit}" 2>/dev/null)" || return 0
  fw tag --points-at "${commit}" --list 'v*' | tr '\n' ' ' | sed 's/ $//'
}

# The copy that runs must be vY's, extracted from the tag — not the framework's working
# tree, not a copy kept from an earlier upgrade.
check_own_copy() {
  local vy="$1" self top
  self="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd -P)/$(basename "${BASH_SOURCE[0]}")"
  top="$(fw rev-parse --show-toplevel)"
  case "${self}" in
    "${top}"/*) check "this copy runs from the framework's working tree (${self}): run the one extracted at ${vy} (SETUP.md, Precondition)" ;;
  esac
  if fw cat-file -e "${vy}:tools/upgrade-check.sh" 2>/dev/null; then
    if fw show "${vy}:tools/upgrade-check.sh" | cmp -s - "${self}"; then
      ok "this copy of upgrade-check.sh is ${vy}'s"
    else
      check "this copy of upgrade-check.sh differs from ${vy}'s: extract it again with git -C \"\$FW\" show ${vy}:tools/upgrade-check.sh"
    fi
  else
    info "${vy} carries no tools/upgrade-check.sh: this copy is newer than the release it checks"
  fi
}

cmd_preflight() {
  [ $# -eq 2 ] || die "usage: preflight vX vY"
  local vx="$1" vy="$2"
  require_fw
  require_project_root
  require_tag "${vx}"
  require_tag "${vy}"

  section "The framework, the project, this script"
  ok "FW is a repository root; the project's root is $(pwd -P); git 2.31 or later"
  check_own_copy "${vy}"
  if fw merge-base --is-ancestor "${vx}" "${vy}"; then
    ok "${vx} is an ancestor of ${vy}"
  else
    fail "${vx} is not an ancestor of ${vy}: an upgrade goes forward, from the pinned release"
  fi
  local releases
  releases="$(fw tag --list 'v*' --sort=v:refname --merged "${vy}" --no-merged "${vx}" | tr '\n' ' ' | sed 's/ $//')"
  info "releases from ${vx} to ${vy}: ${releases:-none}"

  section "The provenance pin (.claude/framework-version)"
  if [ ! -f .claude/framework-version ]; then
    check "no pin: a graft from before the pin existed — vX comes from Step 0's fallbacks, and Step 6 creates the pin"
  else
    local version commit grafted suggestion object type expected
    version="$(pin_field version)"
    commit="$(pin_field commit)"
    grafted="$(pin_field grafted)"
    suggestion=""
    case "${commit}" in
      "" | n/a* | n/d*) ;;
      *) suggestion="$(tags_on "${commit}")" ;;
    esac
    if [[ ! "${version}" =~ ^v[0-9]+\.[0-9]+\.[0-9]+$ ]]; then
      fail "the pin reads 'version: ${version}': it must read 'version: vX.Y.Z', a framework tag with its v — correct the line by hand, nothing normalises it"
      [ -z "${suggestion}" ] || info "SUGGESTION, not applied: the tag on the pinned commit is ${suggestion}"
    elif [ "${version}" != "${vx}" ]; then
      fail "the pin reads ${version} but the upgrade starts from ${vx}: the baseline is the pin's (Step 0)"
    else
      ok "version: ${version}, the upgrade's vX"
    fi
    case "${commit}" in
      "")
        fail "the pin has no 'commit:' line: write 'commit: $(fw rev-parse --short "${vx}^{commit}")', the commit of ${vx}" ;;
      n/d*)
        check "the commit is not recorded ('${commit}'), so the pin's identity cannot be checked; 'n/d' is the placeholder of the Italian releases — write 'n/a' at Step 6" ;;
      n/a*)
        check "the commit is not recorded ('${commit}'), so the pin's identity cannot be checked" ;;
      *)
        object="$(fw rev-parse -q --verify "${commit}" 2>/dev/null)"
        expected="$(fw rev-parse "${vx}^{commit}")"
        if [ -z "${object}" ]; then
          fail "the pinned commit ${commit} does not exist in FW: a pin written from another clone, or a typo"
        else
          type="$(fw cat-file -t "${object}")"
          if [ "${type}" = tag ]; then
            fail "the pinned commit ${commit} is a TAG OBJECT, not a commit: write 'commit: $(fw rev-parse --short "${expected}")' (git -C \"\$FW\" rev-parse ${vx}^{commit})"
          elif [ "${object}" = "${expected}" ]; then
            ok "commit: ${commit}, the commit of ${vx}"
          else
            fail "the pinned commit ${commit} is not the commit of ${vx} ($(fw rev-parse --short "${expected}")): a moved tag, or a pin of another release"
            [ -z "${suggestion}" ] || info "SUGGESTION, not applied: the pinned commit carries ${suggestion}"
          fi
        fi ;;
    esac
    case "${grafted}" in
      "") check "the pin has no 'grafted:' line (the date of the original graft): add it at Step 6" ;;
      n/d*) check "grafted reads '${grafted}': 'n/d' is the placeholder of the Italian releases — write 'n/a' at Step 6" ;;
      *) ok "grafted: ${grafted}" ;;
    esac
  fi

  section "The project's working tree"
  local dirty
  dirty="$(git --no-optional-locks status --porcelain | wc -l | tr -d ' ')"
  if [ "${dirty}" -eq 0 ]; then
    ok "clean: the restore point of Step 1 is the current commit"
  else
    check "${dirty} uncommitted changes: Step 1 starts from a clean working tree"
  fi
  finish "preflight ${vx} -> ${vy}"
}

# --- Reading the framework by tag, through cached listings --------------------------------

# tree_of <tag>: the payload's listing at a tag ("<mode> <type> <blob>\t<path>"), cached.
tree_of() {
  local f="${WORK}/trees/$1"
  if [ ! -f "${f}" ]; then
    mkdir -p "${WORK}/trees"
    fw ls-tree -r "$1" -- "${PAYLOAD_PATHS[@]}" > "${f}.tmp" && mv "${f}.tmp" "${f}"
  fi
  printf '%s\n' "${f}"
}
# blob_at <tag> <path> / mode_at <tag> <path>: from the listing; empty when absent.
blob_at() { awk -F'\t' -v p="$2" '$2 == p { split($1, a, " "); print a[3]; exit }' "$(tree_of "$1")"; }
mode_at() { awk -F'\t' -v p="$2" '$2 == p { split($1, a, " "); print a[1]; exit }' "$(tree_of "$1")"; }
# The releases after vX up to vY, oldest first.
releases_between() { fw tag --list 'v*' --sort=v:refname --merged "$2" --no-merged "$1"; }
# header_region <file>: the lines before the first "## " heading (LEARNINGS.md's template part).
header_region() { awk '/^## /{exit} {print}' "$1"; }
# conflict_lines <file>: the lines inside the conflict markers of a merge's output.
conflict_lines() { awk '/^<<<<<<< /{f=1} f{c++} /^>>>>>>> /{f=0} END{print c+0}' "$1"; }
# marker_count <tag> <path>: the slot markers of a framework file at a tag.
marker_count() { fw show "$1:$2" 2>/dev/null | grep -cE "${MARKER_RE}"; }

# The memory's FORMAT lines (CLAUDE.md, rule 9): what v1.1.0 translated, old form -> new.
# One "old<TAB>new" pair per line; the short forms are those seen in projects.
TITLE_TABLE='## Stato avanzamento	## Progress
## Cosa esiste adesso	## What exists now
## Decisioni prese (non ovvie dal codice)	## Decisions made (not obvious from the code)
## Debito documentazione	## Documentation debt
## Attenzione / problemi aperti	## Caution & open issues
## Branch attivi	## Active branches
## Proposte APERTE (in attesa di decisione utente)	## OPEN proposals (awaiting the user'"'"'s decision)
## Applicate	## Applied
## Rimandate (non respinte — si riprendono al momento giusto)	## Deferred (not rejected — resumed at the right time)
## Rimandate	## Deferred (not rejected — resumed at the right time)
## Rifiutate (con motivo — per non riproporle)	## Rejected (with the reason — so they are not re-proposed)
## Rifiutate	## Rejected (with the reason — so they are not re-proposed)'
# The field labels: at the start of an entry's line, and "| Origin" after the date.
LABEL_TABLE='- Data:	- Date:
| Origine:	| Origin:
- Origine:	- Origin:
- Problema osservato:	- Observed problem:
- Proposta:	- Proposal:
- Beneficio atteso / rischio:	- Expected benefit / risk:
- Trigger di ripresa:	- Resumption trigger:
- Destinazione:	- Destination:'

# normalise_format <file>: the file with its old-form titles and labels in the new form, so
# that the mandatory rename does not read as a change of the memory's content.
normalise_format() {
  # The tables travel in the environment: BSD awk refuses a newline in a -v value.
  UC_TITLES="${TITLE_TABLE}" UC_LABELS="${LABEL_TABLE}" awk '
    BEGIN {
      titles = ENVIRON["UC_TITLES"]; labels = ENVIRON["UC_LABELS"]
      nt = split(titles, tl, "\n")
      for (i = 1; i <= nt; i++) { split(tl[i], kv, "\t"); tmap[kv[1]] = kv[2] }
      nl = split(labels, ll, "\n")
      for (i = 1; i <= nl; i++) { split(ll[i], kv, "\t"); lold[i] = kv[1]; lnew[i] = kv[2] }
    }
    {
      line = $0
      if (line in tmap) line = tmap[line]
      for (i = 1; i <= nl; i++) {
        p = index(line, lold[i])
        if (p == 0) continue
        if (substr(lold[i], 1, 1) == "|") {
          if (line ~ /^- (Data|Date):/) line = substr(line, 1, p - 1) lnew[i] substr(line, p + length(lold[i]))
        } else if (p == 1) {
          line = lnew[i] substr(line, length(lold[i]) + 1)
        }
      }
      print line
    }' "$1"
}

# old_labels <file>: the lines that still carry an old-form label, outside comments.
old_labels() {
  awk '/<!--/{c=1} !c && /^- (Data|Origine|Problema osservato|Proposta|Beneficio atteso \/ rischio|Trigger di ripresa|Destinazione):/{n++} /-->/{c=0} END{print n+0}' "$1"
}

# missing_titles <tag> <memory file>: vY's "## " titles the project's file lacks.
missing_titles() {
  local own="${WORK}/titles.own"
  grep '^## ' "$2" > "${own}" 2>/dev/null || : > "${own}"
  fw show "$1:$2" 2>/dev/null | grep '^## ' | grep -vxF -f "${own}" || true
}

cmd_inventory() {
  [ $# -eq 2 ] || die "usage: inventory vX vY"
  local vx="$1" vy="$2"
  require_fw
  require_project_root
  require_tag "${vx}"
  require_tag "${vy}"
  require_t
  local d="${WORK}/inventory"
  rm -rf "${d}" && mkdir -p "${d}" || die "cannot prepare ${d}"
  local releases
  releases="$(releases_between "${vx}" "${vy}" | tr '\n' ' ')"

  section "Files — class, the framework vX->vY (=, M, A, D), the project against the tags, the 3-way's measure"
  local path class bx by bp fwst prj measure n mine base theirs r prev changed modey modep
  { awk -F'\t' '{print $2}' "$(tree_of "${vx}")"; awk -F'\t' '{print $2}' "$(tree_of "${vy}")"; } | sort -u > "${d}/paths"
  while IFS= read -r path; do
    class="$(classify "${path}")"
    case "${class}" in
      PROJECT-MEMORY | LOCAL | GRAFT-STATE) continue ;;
      NONE) fail "no class for ${path} (a payload file of ${vx} or ${vy})"; continue ;;
    esac
    bx="$(blob_at "${vx}" "${path}")"
    by="$(blob_at "${vy}" "${path}")"
    if [ -z "${bx}" ]; then fwst=A; elif [ -z "${by}" ]; then fwst=D; elif [ "${bx}" = "${by}" ]; then fwst="="; else fwst=M; fi
    # LEARNINGS.md: only its header region is the framework's.
    if [ "${class}" = LEARNINGS ]; then
      header_region "${path}" > "${d}/lrn.mine" 2>/dev/null
      fw show "${vx}:${path}" | header_region /dev/stdin > "${d}/lrn.base"
      fw show "${vy}:${path}" | header_region /dev/stdin > "${d}/lrn.theirs"
      if cmp -s "${d}/lrn.base" "${d}/lrn.theirs"; then fwst="="; else fwst=M; fi
      if cmp -s "${d}/lrn.mine" "${d}/lrn.theirs"; then prj="=vY"; elif cmp -s "${d}/lrn.mine" "${d}/lrn.base"; then prj="=vX"; else prj=diverged; fi
      mine="${d}/lrn.mine"; base="${d}/lrn.base"; theirs="${d}/lrn.theirs"
    else
      if [ -f "${path}" ]; then
        bp="$(git hash-object -- "${path}")"
        if [ "${bp}" = "${by}" ]; then prj="=vY"; elif [ "${bp}" = "${bx}" ]; then prj="=vX"; else prj=diverged; fi
      else
        prj=absent
      fi
      mine="${path}"; base="${d}/base"; theirs="${d}/theirs"
      [ "${fwst}" = M ] && { fw show "${vx}:${path}" > "${base}"; fw show "${vy}:${path}" > "${theirs}"; }
    fi
    measure=""
    if [ "${fwst}" = M ] && [ "${prj}" = diverged ]; then
      git merge-file -p "${mine}" "${base}" "${theirs}" > "${d}/merged" 2>/dev/null
      n=$?
      measure="3-way: ${n} conflict(s), $(conflict_lines "${d}/merged") of $(wc -l < "${d}/merged" | tr -d ' ') lines in conflict"
    fi
    [ "${class}" = LEARNINGS ] && path="${path} (header)"
    info "$(printf '%-9s %-2s %-9s %s%s' "${class}" "${fwst}" "${prj}" "${path}" "${measure:+ — ${measure}}")"
    path="${path% (header)}"
    # The flags of the edge cases (SETUP.md, *Edge cases*).
    [ "${class}" = METHOD ] && [ "${prj}" = diverged ] && [ "${fwst}" != D ] \
      && check "edge case 7: ${path} is METHOD but customised in the project — reconcile it as a HYBRID (3-way), never overwrite"
    [ "${fwst}" = D ] && [ "${prj}" != absent ] && check "edge case 1: ${path} is deleted in ${vy} — remove it from the project (git rm), after checking it holds nothing of the project's"
    [ "${fwst}" = A ] && [ "${prj}" = diverged ] && check "${path} is new in ${vy}, but the project already has a file there: compare before taking ${vy}'s"
    [ "${path}" = .gitignore ] && [ "${fwst}" = M ] && info "  .gitignore: an additive union (Step 3), not a 3-way"
    if [ "${fwst}" = M ]; then
      changed=""; prev="${vx}"
      for r in ${releases}; do
        [ "$(blob_at "${prev}" "${path}")" = "$(blob_at "${r}" "${path}")" ] || changed="${changed} ${r}"
        prev="${r}"
      done
      [ "$(echo ${changed} | wc -w | tr -d ' ')" -gt 1 ] \
        && check "edge case 6: ${path} changed in${changed} — if its 3-way is intricate, reconcile one release at a time"
    fi
    if [ -n "${by}" ] && [ -f "${path}" ]; then
      modey="$(mode_at "${vy}" "${path}")"
      if [ -x "${path}" ]; then modep=100755; else modep=100644; fi
      [ "${modey}" = "${modep}" ] || check "${path}: ${vy}'s mode is ${modey}, the project's ${modep} (chmod after the copy, Step 3)"
    fi
  done < "${d}/paths"
  local renames
  renames="$(fw diff -M --name-status "${vx}" "${vy}" -- "${PAYLOAD_PATHS[@]}" | awk -F'\t' '$1 ~ /^R/ {print $2 " -> " $3}')"
  [ -z "${renames}" ] || while IFS= read -r r; do check "edge case 2: renamed in ${vy}: ${r} — move it, never keep both"; done <<< "${renames}"

  section "Markers — slots added or removed between ${vx} and ${vy}"
  local added="" removed="" mx my
  while IFS= read -r path; do
    case "$(classify "${path}")" in METHOD | HYBRID | TEMPLATE | LEARNINGS) ;; *) continue ;; esac
    mx="$(marker_count "${vx}" "${path}")"; my="$(marker_count "${vy}" "${path}")"
    [ "${my}" -gt "${mx}" ] && added="${added} ${path}(+$((my - mx)))"
    [ "${mx}" -gt "${my}" ] && removed="${removed} ${path}(-$((mx - my)))"
  done < "${d}/paths"
  if [ -n "${added}" ] && [ -n "${removed}" ]; then
    check "markers removed in${removed} and added in${added}: a slot may have MOVED — if the project answered it in the old file, carry the answer to the new one first (edge case 8)"
  elif [ -n "${added}" ]; then
    check "new slots in${added}: fill them with the project's answers (Step 4)"
  elif [ -n "${removed}" ]; then
    info "slots removed in${removed}"
  else
    ok "no slot added or removed"
  fi

  section "The §2 checklist of SETUP.md — items added or re-worded between ${vx} and ${vy}"
  local s2x="${d}/s2.x" s2y="${d}/s2.y"
  for r in "${vx}:${s2x}" "${vy}:${s2y}"; do
    fw show "${r%%:*}:SETUP.md" 2>/dev/null | awk '/^## 2\./{f=1;next} /^## 3\./{f=0} f' | grep '^- \[ \]' | sort > "${r#*:}" || true
  done
  if [ ! -s "${s2y}" ]; then
    info "no §2 checklist in ${vy}'s SETUP.md"
  elif cmp -s "${s2x}" "${s2y}"; then
    ok "the §2 checklist is unchanged"
  else
    comm -13 "${s2x}" "${s2y}" > "${d}/s2.added"
    comm -23 "${s2x}" "${s2y}" > "${d}/s2.removed"
    while IFS= read -r line; do check "§2, new or re-worded: ${line#- \[ \] }"; done < "${d}/s2.added"
    while IFS= read -r line; do info "§2, gone or re-worded: ${line#- \[ \] }"; done < "${d}/s2.removed"
  fi

  section "The memory's format — titles and field labels to rename (edge case 3 (b))"
  local f t pending=0 labels
  for f in .claude/memory/STATE.md .claude/memory/LEARNINGS.md; do
    [ -f "${f}" ] || { info "${f}: absent in the project"; continue; }
    while IFS= read -r t; do
      [ -n "${t}" ] || continue
      check "${f} lacks ${vy}'s title '${t}': rename the old one (the table of edge case 3 (b))"
      pending=$((pending + 1))
    done <<< "$(missing_titles "${vy}" "${f}")"
  done
  if [ -f .claude/memory/LEARNINGS.md ]; then
    labels="$(old_labels .claude/memory/LEARNINGS.md)"
    [ "${labels}" -eq 0 ] || { check "${labels} line(s) of LEARNINGS.md carry an old-form field label: rename them (the table of edge case 3 (b))"; pending=$((pending + 1)); }
  fi
  [ "${pending}" -gt 0 ] || ok "titles and field labels already in ${vy}'s form"

  section "The Upgrading notes of the releases after ${vx}, oldest first — different topics add up; on the same topic the most recent wins (Step 2)"
  fw show "${vy}:CHANGELOG.md" > "${d}/changelog" 2>/dev/null || : > "${d}/changelog"
  for r in ${releases}; do
    awk -v h="## [${r#v}]" '
      index($0, h) == 1 { s = 1; next }
      s && /^## \[/ { exit }
      s && /^\*\*Upgrading/ { u = 1 }
      s && u { l[++n] = $0; if (NF) last = n }
      END { for (i = 1; i <= last; i++) print l[i] }' "${d}/changelog" > "${d}/note"
    if [ -s "${d}/note" ]; then
      info "${r}:"
      sed 's/^/       | /' "${d}/note"
    else
      info "${r}: no Upgrading paragraph — read its entry in ${vy}'s CHANGELOG"
    fi
  done
  finish "inventory ${vx} -> ${vy}"
}

# format_done <vY>: after the rename, no title of vY missing and no old-form label (FAIL).
format_done() {
  local vy="$1" f t pending=0
  section "The memory's format — titles and field labels (edge case 3 (b))"
  for f in .claude/memory/STATE.md .claude/memory/LEARNINGS.md; do
    [ -f "${f}" ] || continue
    while IFS= read -r t; do
      [ -n "${t}" ] || continue
      fail "${f} still lacks ${vy}'s title '${t}': the rename is mandatory"
      pending=$((pending + 1))
    done <<< "$(missing_titles "${vy}" "${f}")"
  done
  if [ -f .claude/memory/LEARNINGS.md ] && [ "$(old_labels .claude/memory/LEARNINGS.md)" -gt 0 ]; then
    fail "$(old_labels .claude/memory/LEARNINGS.md) line(s) of LEARNINGS.md still carry an old-form field label: the rename is mandatory"
    pending=$((pending + 1))
  fi
  [ "${pending}" -gt 0 ] || ok "titles and field labels in ${vy}'s form"
}

# --- invariant -------------------------------------------------------------------------

# body_region <file>: from the first "## " heading to the end (LEARNINGS.md's memory part).
body_region() { awk '/^## /{b=1} b' "$1"; }
# comments_of <file>: its comment blocks, each closed by a line "@@END".
comments_of() { awk '/<!--/{c=1} c{print} /-->/{if (c) print "@@END"; c=0}' "$1"; }
# without_comments <file>: the file without its comment blocks.
without_comments() { awk '/<!--/{c=1} !c{print} /-->/{c=0}' "$1"; }
# show_diff <a> <b>: the first lines of a unified diff, indented, for a human to read.
show_diff() { diff -u "$1" "$2" | sed -n '3,40p' | sed 's/^/       | /'; }

cmd_invariant() {
  [ $# -eq 3 ] || die "usage: invariant vX vY <restore point: the project's pre-upgrade commit>"
  local vx="$1" vy="$2" restore="$3"
  require_fw
  require_project_root
  require_tag "${vx}"
  require_tag "${vy}"
  require_t
  git rev-parse -q --verify "${restore}^{commit}" >/dev/null || die "the restore point ${restore} is not a commit of the project"
  local d="${WORK}/invariant"
  rm -rf "${d}" && mkdir -p "${d}" || die "cannot prepare ${d}"

  section "The touches on .claude/memory/ since the restore point ${restore} — a closed list (SETUP.md, Step 5)"
  { git --no-optional-locks diff --name-status --no-renames "${restore}" -- .claude/memory
    git --no-optional-locks ls-files --others --exclude-standard -- .claude/memory | awk '{ print "A\t" $0 }'
  } > "${d}/changes"
  [ -s "${d}/changes" ] || ok "no change under .claude/memory/"
  local st path class bad mnow mrest mx my
  while IFS=$'\t' read -r st path; do
    [ -n "${path}" ] || continue
    class="$(classify "${path}")"
    if [ "${st}" = D ]; then
      fail "${path} is deleted: an upgrade removes nothing from the memory"
      continue
    fi
    case "${class}" in
      TEMPLATE)
        if [ "$(git hash-object -- "${path}")" = "$(blob_at "${vy}" "${path}")" ]; then
          ok "${path}: the memory template at ${vy}"
        else
          check "${path}: a memory template that differs from ${vy}'s — fine only for the project's own customisation, kept through the 3-way:"
          fw show "${vy}:${path}" > "${d}/template"
          show_diff "${d}/template" "${path}"
        fi
        # A slot answered at the restore point must not be open again.
        mnow="$(grep -cE "${MARKER_RE}" "${path}")"
        mrest="$(git show "${restore}:${path}" 2>/dev/null | grep -cE "${MARKER_RE}")"
        mx="$(marker_count "${vx}" "${path}")"; my="$(marker_count "${vy}" "${path}")"
        [ $((mnow - mrest)) -le $((my - mx)) ] \
          || fail "${path}: a slot the project had answered is open again — re-apply its answer" ;;
      LEARNINGS)
        info "${path}: see its own section below" ;;
      PROJECT-MEMORY)
        case "${st}:${path}" in
          *:.claude/memory/STATE.md | *:.claude/memory/TREE.md | *:.claude/memory/INDEX.md)
            info "${path}: rewritten by the upgrade's checkpoint (Step 6)" ;;
          A:.claude/memory/sessions/* | A:.claude/memory/plans/*)
            ok "${path}: added — the upgrade's own session note or plan" ;;
          A:*)
            fail "${path}: added outside the upgrade's own note and plan" ;;
          *)
            # Only edge case 3 (a): a line that changes carries a pointer.
            bad="$(git --no-optional-locks diff -U0 "${restore}" -- "${path}" \
              | grep -E '^[-+]' | grep -vE '^(\+\+\+|---) ' | grep -vE '\[\[|\.md|docs/' | head -n 1)"
            if [ -z "${bad}" ]; then
              ok "${path}: pointer repairs only (edge case 3 (a))"
            else
              fail "${path}: changed beyond the pointer repairs of edge case 3 (a): ${bad}"
            fi ;;
        esac ;;
      *)
        fail "${path}: ${class} — not a file an upgrade touches under .claude/memory/" ;;
    esac
  done < "${d}/changes"

  section "LEARNINGS.md — the header is a template; the IMP entries are the project's memory"
  local f=.claude/memory/LEARNINGS.md
  if [ ! -f "${f}" ]; then
    info "${f}: absent"
  else
    header_region "${f}" > "${d}/h.now"
    fw show "${vy}:${f}" > "${d}/vy.learnings"
    header_region "${d}/vy.learnings" > "${d}/h.vy"
    if cmp -s "${d}/h.now" "${d}/h.vy"; then
      ok "the header is ${vy}'s"
    else
      check "the header differs from ${vy}'s — fine only for the project's own text, kept through the 3-way:"
      show_diff "${d}/h.vy" "${d}/h.now"
    fi
    body_region "${f}" > "${d}/b.now"
    body_region "${d}/vy.learnings" > "${d}/b.vy"
    git show "${restore}:${f}" 2>/dev/null | body_region /dev/stdin > "${d}/b.before"
    comments_of "${d}/b.now" > "${d}/c.now"
    comments_of "${d}/b.vy" > "${d}/c.vy"
    local cnow cvy
    cnow="$(grep -c '^@@END$' "${d}/c.now")"; cvy="$(grep -c '^@@END$' "${d}/c.vy")"
    if [ "${cnow}" -ne "${cvy}" ]; then
      fail "the body has ${cnow} comment block(s), ${vy}'s format has ${cvy}: an extra block can hide an IMP entry"
    elif cmp -s "${d}/c.now" "${d}/c.vy"; then
      ok "the format comment is ${vy}'s"
    else
      check "the format comment differs from ${vy}'s — a project's rewording, or an entry hidden inside it:"
      show_diff "${d}/c.vy" "${d}/c.now"
    fi
    # Blank lines carry no content, and replacing a format comment moves them: they are
    # left out of the comparison, as the old-form titles and labels are normalised.
    without_comments "${d}/b.before" > "${d}/e.before.raw"
    normalise_format "${d}/e.before.raw" | awk 'NF' > "${d}/e.before"
    without_comments "${d}/b.now" > "${d}/e.now.raw"
    normalise_format "${d}/e.now.raw" | awk 'NF' > "${d}/e.now"
    if cmp -s "${d}/e.before" "${d}/e.now"; then
      ok "the IMP entries are unchanged (titles and field labels compared in their new form, blank lines aside)"
    else
      fail "the IMP entries changed — an upgrade never edits them:"
      show_diff "${d}/e.before" "${d}/e.now"
    fi
  fi

  format_done "${vy}"
  finish "invariant ${vx} -> ${vy}, since ${restore}"
}

# --- post --------------------------------------------------------------------------------

cmd_post() {
  [ $# -eq 2 ] || die "usage: post vX vY"
  local vx="$1" vy="$2"
  require_fw
  require_project_root
  require_tag "${vx}"
  require_tag "${vy}"
  require_t
  local d="${WORK}/post" path class by n_at=0 modey modep
  rm -rf "${d}" && mkdir -p "${d}" || die "cannot prepare ${d}"

  section "The payload against ${vy} — METHOD files at ${vy}, every file present, modes"
  awk -F'\t' '{print $2}' "$(tree_of "${vy}")" > "${d}/paths.vy"
  while IFS= read -r path; do
    class="$(classify "${path}")"
    case "${class}" in PROJECT-MEMORY | LOCAL | GRAFT-STATE | LEARNINGS) continue ;; esac
    if [ ! -f "${path}" ]; then
      fail "${path} (${class}) is missing: bring it over from ${vy}"
      continue
    fi
    by="$(blob_at "${vy}" "${path}")"
    case "${class}" in
      METHOD)
        if [ "$(git hash-object -- "${path}")" = "${by}" ]; then
          n_at=$((n_at + 1))
        else
          check "${path} (METHOD) differs from ${vy}'s: fine only if it was reconciled as a hybrid (edge case 7)"
        fi ;;
      TEMPLATE)
        [ "$(git hash-object -- "${path}")" = "${by}" ] && n_at=$((n_at + 1)) \
          || check "${path} (TEMPLATE) differs from ${vy}'s: fine only for the project's own customisation" ;;
      NONE) fail "no class for ${path}" ;;
    esac
    modey="$(mode_at "${vy}" "${path}")"
    if [ -x "${path}" ]; then modep=100755; else modep=100644; fi
    [ "${modey}" = "${modep}" ] || fail "${path}: mode ${modep}, ${vy}'s is ${modey} (chmod, Step 3)"
  done < "${d}/paths.vy"
  ok "${n_at} METHOD and TEMPLATE files identical to ${vy}'s"
  # Orphans: what vY removed must be gone from the project too.
  awk -F'\t' '{print $2}' "$(tree_of "${vx}")" | sort > "${d}/paths.vx.sorted"
  sort "${d}/paths.vy" > "${d}/paths.vy.sorted"
  comm -23 "${d}/paths.vx.sorted" "${d}/paths.vy.sorted" | while IFS= read -r path; do
    case "$(classify "${path}")" in PROJECT-MEMORY | LOCAL | GRAFT-STATE) continue ;; esac
    [ -e "${path}" ] && echo "${path}"
  done > "${d}/orphans"
  if [ -s "${d}/orphans" ]; then
    while IFS= read -r path; do fail "${path} is an orphan: ${vy} removed it (edge case 1)"; done < "${d}/orphans"
  else
    ok "no orphan of a file ${vy} removed"
  fi

  section "Slots — markers broken by a wrap, and the slots ${vy} added"
  local mx my
  while IFS= read -r path; do
    case "$(classify "${path}")" in METHOD | HYBRID | TEMPLATE | LEARNINGS) ;; *) continue ;; esac
    [ -f "${path}" ] || continue
    # Read from a file, not a pipe: a loop on a pipe runs in a subshell, and its FAILs
    # would not be counted.
    grep -nE "${BROKEN_MARKER_RE}" "${path}" > "${d}/broken" || true
    while IFS= read -r line; do
      fail "${path}:${line} — a marker broken by a line wrap: keep it on one line"
    done < "${d}/broken"
    mx="$(marker_count "${vx}" "${path}")"; my="$(marker_count "${vy}" "${path}")"
    if [ "${my}" -gt "${mx}" ]; then
      check "${vy} added $((my - mx)) slot(s) to ${path}: confirm the project's answer is in place, not the framework's default:"
      grep -nE -A1 "${MARKER_RE}" "${path}" | sed 's/^/       | /'
    fi
  done < "${d}/paths.vy"

  section "Hooks — every hook of the project's scripts/hooks-install.sh is installed (Step 4)"
  local hooks h n_h=0
  hooks="$(git rev-parse --path-format=absolute --git-common-dir)/hooks"
  for h in $(sed -n 's/^for hook in \(.*\); do$/\1/p' scripts/hooks-install.sh 2>/dev/null); do
    n_h=$((n_h + 1))
    if grep -qF "${HOOK_MARKER}" "${hooks}/${h}" 2>/dev/null; then
      ok "${h} installed, with the generator's marker"
    else
      fail "${h} missing or foreign in ${hooks}: run make hooks-install"
    fi
  done
  [ "${n_h}" -gt 0 ] || fail "no hook list found in scripts/hooks-install.sh"

  format_done "${vy}"

  section "The provenance pin"
  local version
  version="$( [ -f .claude/framework-version ] && pin_field version )"
  if [ "${version}" = "${vy}" ]; then
    ok "the pin reads ${vy}"
  elif [ "${version}" = "${vx}" ] || [ -z "${version}" ]; then
    check "the pin reads '${version:-nothing}': Step 6 writes 'version: ${vy}' and its commit"
  else
    fail "the pin reads '${version}', neither ${vx} nor ${vy}"
  fi
  finish "post ${vx} -> ${vy}"
}

main() {
  [ $# -ge 1 ] || die "usage: upgrade-check.sh classes|preflight|inventory|invariant|post ..."
  local sub="$1"
  shift
  case "${sub}" in
    classes) cmd_classes "$@" ;;
    preflight) cmd_preflight "$@" ;;
    inventory) cmd_inventory "$@" ;;
    invariant) cmd_invariant "$@" ;;
    post) cmd_post "$@" ;;
    *) die "unknown subcommand: ${sub}" ;;
  esac
}

main "$@"
