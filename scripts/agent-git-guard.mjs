#!/usr/bin/env node
// agent-git-guard — PreToolUse hook for the Bash, PowerShell and Monitor tools: delegated
// agents are read-only on git (docs/04, "Delegated agents and the shared working tree").
//
// WHAT. When the hook input carries `agent_id` — the call comes from a delegated agent:
// a subagent or a workflow agent — every git command in it must be a read. The main
// session carries no `agent_id` and is never restricted: docs/04 gives it the local
// branch work.
// WHY. Agents told "read-only" in their prompt still ran checkout/switch/archive in the
// shared working tree: a sentence in a prompt is not a boundary, this hook is. A linked
// worktree is no exception: it shares refs, config, stash and objects with the repo.
// SCOPE — the threat model of docs/04 ("Enforcement of the execution boundary"): an
// agent's ACCIDENTAL errors with ordinary commands. The command is read the way the
// agent wrote it: split on shell operators, git found after leading assignments, shell
// keywords, a few wrapper commands and git's own global options (-C, -c, --git-dir,
// ...). The PowerShell tool's commands are read the same way, in PowerShell's syntax —
// its backtick escape, script blocks, assignments, here-strings, block comments; the
// framework keeps that tool off (settings.json), and the guard still reads it for a
// developer who turns it on. Whatever the spelling —
// `/usr/bin/git`, `C:\Program Files\Git\cmd\git.exe`, `Git` — git is git: Windows and macOS
// find commands without regard to case. It does NOT look inside `sh -c`, `eval`, scripts
// or interpreter code, nor behind a wrapper it does not list (`sudo`, `find -exec`); nor
// does it see git in an unquoted heredoc's `$(…)` or backticks, in a function declared
// with `function` and no parentheses, in a `coproc`, or as a command name held in a
// variable. Its coverage is the forms its self-test holds; docs/04 lists the rest as
// outside this layer. Pushes are not its job either: the pre-push hook generated by
// scripts/hooks-install.sh refuses every push launched from an agent session.
// CONTRACT. stdin: the hook JSON. Exit 0: no objection (the permission flow goes on).
// Exit 2: blocked, the reason on stderr (the agent reads it). Exit 3: unreadable input — a
// FAILURE, not a verdict. .claude/settings.json lets a verdict (0 or 2) stand and turns
// any failure — exit 3, a crash, a missing file, a missing `node` — into a block when the
// input carries the agent_id key (fail-closed for delegated agents) and, otherwise, into
// a non-blocking error (exit 1) that the transcript shows: the guard has no job in the
// main session, but its failure must not go unnoticed.
// Self-test: scripts/test-agent-git-guard.sh.
import { readFileSync } from 'node:fs';

const BLOCKED = 2;
const FAILED = 3; // not a verdict: the wiring in settings.json decides

// Subcommands that only read. Anything not listed here or in READ_FORMS is refused:
// an allow-list, so an unknown subcommand or an ad-hoc alias (`-c alias.x=...`) is
// refused too.
const READ_ONLY = new Set([
  'annotate', 'blame', 'cat-file', 'check-attr', 'check-ignore', 'check-ref-format',
  'cherry', 'count-objects', 'describe', 'diff', 'diff-files', 'diff-index', 'diff-tree',
  'for-each-ref', 'grep', 'help', 'log', 'ls-files', 'ls-tree', 'merge-base', 'name-rev',
  'range-diff', 'rev-list', 'rev-parse', 'shortlog', 'show', 'show-branch', 'show-ref',
  'var', 'verify-commit', 'verify-tag', 'version', 'whatchanged',
]);

// Subcommands that read in some forms and write in others. `a` = the arguments after
// the subcommand; each predicate is true for the READ forms only.
const nonFlags = (a) => a.filter((x) => !x.startsWith('-'));
const flagNames = (a) => a.filter((x) => x.startsWith('-')).map((x) => x.split('=')[0].replace(/^-n\d+$/, '-n'));
const listing = (a, listFlags, writeFlags) => {
  const flags = flagNames(a);
  if (flags.some((f) => writeFlags.includes(f))) return false;
  return nonFlags(a).length === 0 || flags.some((f) => listFlags.includes(f));
};
const READ_FORMS = {
  // `git branch` / `git tag` with no name, or with a flag that switches to LIST mode;
  // `git branch x` creates — and so does `git branch -v x`: -v, --sort, --format only
  // shape a listing, they do not request one.
  branch: (a) => listing(a,
    ['-a', '--all', '-r', '--remotes', '-l', '--list', '--contains', '--no-contains', '--merged',
      '--no-merged', '--points-at'],
    ['-d', '-D', '--delete', '-m', '-M', '--move', '-c', '-C', '--copy', '-f', '--force', '-u',
      '--set-upstream-to', '--unset-upstream', '--edit-description', '-t', '--track', '--create-reflog']),
  tag: (a) => listing(a,
    ['-l', '--list', '-n', '--contains', '--no-contains', '--merged', '--no-merged', '--points-at',
      '-v', '--verify'],
    ['-a', '--annotate', '-s', '--sign', '-u', '--local-user', '-f', '--force', '-d', '--delete',
      '-m', '--message', '-F', '--file', '-e', '--edit', '--create-reflog']),
  stash: (a) => a[0] === 'list' || a[0] === 'show',
  worktree: (a) => a[0] === 'list',
  notes: (a) => a[0] === 'list' || a[0] === 'show',
  remote: (a) => nonFlags(a).length === 0 || nonFlags(a)[0] === 'get-url',
  reflog: (a) => !['expire', 'delete', 'drop', 'write'].includes(a[0]),
  'symbolic-ref': (a) => nonFlags(a).length <= 1 && !flagNames(a).some((f) => ['-d', '--delete'].includes(f)),
  // `git config <name>` reads, `git config <name> <value>` writes.
  config: (a) => {
    const flags = flagNames(a); const words = nonFlags(a);
    const writes = ['--add', '--unset', '--unset-all', '--replace-all', '--rename-section',
      '--remove-section', '-e', '--edit', 'set', 'unset', 'rename-section', 'remove-section', 'edit'];
    if ([...flags, ...words].some((x) => writes.includes(x))) return false;
    const reads = ['--get', '--get-all', '--get-regexp', '--get-urlmatch', '-l', '--list', 'get', 'list'];
    return [...flags, ...words].some((x) => reads.includes(x)) || words.length === 1;
  },
  // To stdout only: `-o`/`--output` would write a file (2026-09-24: an archive left in
  // the repo root).
  archive: (a) => !flagNames(a).some((f) => f.startsWith('-o') || f === '--output'),
};

// git's global options that take their value as the NEXT word (git(1), OPTIONS).
const GIT_OPTIONS_WITH_VALUE = new Set(['-C', '-c', '--git-dir', '--work-tree', '--namespace',
  '--config-env', '--super-prefix', '--attr-source']);

// Words that may precede the command without being it.
const SHELL_KEYWORDS = new Set(['!', '{', '}', 'if', 'then', 'else', 'elif', 'do', 'while', 'until']);
// Wrapper commands that run the word after them as the command, with the options that
// take a separate value: the wrappers Claude Code strips before matching a Bash rule (its
// permissions documentation) — xargs there only bare —, and env and exec besides.
const WRAPPERS = {
  env: ['-u', '--unset', '-C', '--chdir'], command: [], builtin: [], exec: [], nohup: [],
  time: [], noglob: [], nice: ['-n', '--adjustment'], stdbuf: ['-i', '-o', '-e'],
  timeout: ['-s', '--signal', '-k', '--kill-after'],
  xargs: ['-I', '-L', '-n', '-P', '-s', '-d', '-E', '-a', '-J', '-R', '-S'],
};
const ASSIGNMENT = /^[A-Za-z_][A-Za-z0-9_]*=/;
const REDIRECTION = /^[0-9&]*[<>]/; // `2>/dev/null`, `>out`, `2>&1`; a bare `>` takes the next word

// Splits a command line into simple commands (arrays of words), the way a shell sees
// them: quotes, backslashes and line continuations are honoured; ; & | ( ) ` and
// newlines separate commands, so `cd x && git switch y` and `v=$(git switch y)` both
// surface `git switch y`, as does a `$(...)` inside double quotes; heredoc bodies are
// skipped as data, though an unquoted one runs its `$(…)` and backticks, unread here.
// Inside double quotes a backslash escapes only $ ` " \ and a line end, as in bash:
// `"C:\Program Files\Git\cmd\git.exe"` keeps its backslashes.
// Deliberately small: no expansion, and no look inside a string handed to another shell
// (`sh -c`, `eval`). PowerShell's text (`powershell` true) differs: its escape is the
// backtick — a backtick before a line end continues the line —, so a backslash is an
// ordinary character there, as in a Windows path; braces separate commands too (script
// blocks: `try { git … }`, `| ForEach-Object { git … }`), but `${name}` stays a variable;
// `<#…#>` is a comment; and a here-string is data — `@'…'@` all of it, `@"…"@` but for its
// `$(…)`, read as in double quotes.
function splitCommands(text, powershell = false) {
  const escape = powershell ? '`' : '\\';
  const separators = powershell ? ';&|(){}' : ';&|()`';
  const commands = [];
  // The commands a `$(…)` runs inside a string body (up to its first closing parenthesis).
  const substitutions = (body) => {
    for (let k = body.indexOf('$('); k >= 0; k = body.indexOf('$(', k + 2)) {
      const end = body.indexOf(')', k + 2);
      commands.push(...splitCommands(body.slice(k + 2, end < 0 ? body.length : end), powershell));
    }
  };
  const heredocs = [];
  let words = [];
  let word = null;
  const endWord = () => { if (word !== null) { words.push(word); word = null; } };
  const endCommand = () => { endWord(); if (words.length) commands.push(words); words = []; };
  let i = 0;
  while (i < text.length) {
    const c = text[i];
    if (c === escape && text[i + 1] === '\n') { i += 2; continue; } // a line continuation
    if (c === escape) { word = (word ?? '') + (text[i + 1] ?? ''); i += 2; continue; }
    if (powershell && text.startsWith('${', i)) { // ${name} is a variable, not a script block
      const end = text.indexOf('}', i + 2);
      const stop = end < 0 ? text.length : end + 1;
      word = (word ?? '') + text.slice(i, stop); i = stop; continue;
    }
    if (powershell && text.startsWith('<#', i)) { // a block comment: a word break, nothing more
      endWord();
      const end = text.indexOf('#>', i + 2);
      i = end < 0 ? text.length : end + 2; continue;
    }
    const here = powershell && c === '@' && /^@(['"])[ \t]*\n/.exec(text.slice(i, i + 80));
    if (here) { // a here-string: its body runs from the next line to a line that starts with '@ or "@
      const start = text.indexOf('\n', i) + 1;
      const end = text.indexOf(`\n${here[1]}@`, start - 1); // start - 1: an empty body
      const body = end < 0 ? text.slice(start) : text.slice(start, Math.max(start, end));
      if (here[1] === '"') substitutions(body);
      word = (word ?? '') + body; i = end < 0 ? text.length : end + 3; continue;
    }
    if (c === "'") {
      const end = text.indexOf("'", i + 1);
      const stop = end < 0 ? text.length : end;
      word = (word ?? '') + text.slice(i + 1, stop); i = stop + 1; continue;
    }
    if (c === '"') {
      let j = i + 1; let s = '';
      while (j < text.length && text[j] !== '"') {
        if (text.startsWith('$(', j) || (!powershell && text[j] === '`')) { // "$(git x)" still runs git x
          const open = text[j] === '`' ? 1 : 2;
          const end = text.indexOf(open === 1 ? '`' : ')', j + open);
          const stop = end < 0 ? text.length : end;
          commands.push(...splitCommands(text.slice(j + open, stop), powershell)); j = stop + 1; continue;
        }
        if (text[j] === escape && j + 1 < text.length && (powershell || '$`"\\\n'.includes(text[j + 1]))) {
          s += text[j + 1]; j += 2;
        } else { s += text[j]; j += 1; }
      }
      word = (word ?? '') + s; i = j + 1; continue;
    }
    if (c === '#' && word === null) { while (i < text.length && text[i] !== '\n') i += 1; continue; }
    if (c === '<' && text.startsWith('<<', i) && text[i + 2] !== '<') {
      const m = /^<<-?[ \t]*(['"]?)([A-Za-z0-9_.-]+)\1/.exec(text.slice(i));
      if (m) { endWord(); heredocs.push(m[2]); i += m[0].length; continue; }
    }
    if (c === '\n') {
      endCommand(); i += 1;
      while (heredocs.length) { // skip each pending heredoc body up to its delimiter line
        const delimiter = heredocs.shift();
        while (i < text.length) {
          const eol = text.indexOf('\n', i) < 0 ? text.length : text.indexOf('\n', i);
          const line = text.slice(i, eol); i = eol + 1;
          if (line.replace(/^\t+/, '') === delimiter) break;
        }
      }
      continue;
    }
    if (c === ' ' || c === '\t') { endWord(); i += 1; continue; }
    if (separators.includes(c)) { endCommand(); i += 1; continue; }
    word = (word ?? '') + c; i += 1;
  }
  endCommand();
  return commands;
}

// The name a word runs as a command: its last path component (after a /, or a Windows \),
// in lower case and without Windows' .exe — `/usr/bin/git`, `git.exe`, `Git` and
// `C:\Program Files\Git\cmd\git.exe` all run git.
const commandName = (word) => (word ?? '').split(/[\\/]/).pop().toLowerCase().replace(/\.exe$/, '');

// PowerShell runs the command that follows an assignment — `$out = git …`,
// `[string]$s = git …`, `$log += git …`, glued as `$out=git …` — and a dot-sourced one,
// `. git …`: those leading words go, the command stays.
const PS_TARGET = /^(?:\[[^\]]*\])*\$/;
const PS_ASSIGNED = /^(?:\[[^\]]*\])*\$[^=]*?(?:[-+*/%]|\?\?)?=(.*)$/s; // target and operator in one word
const PS_OPERATOR = /^(?:[-+*/%]|\?\?)?=(.*)$/s; // the operator, maybe glued to what follows
function skipPowerShellPrefix(words) {
  let rest = words;
  for (;;) {
    if (rest[0] === '.') { rest = rest.slice(1); continue; }
    if (!PS_TARGET.test(rest[0] ?? '')) return rest;
    const glued = PS_ASSIGNED.exec(rest[0]);
    if (glued) { rest = glued[1] ? [glued[1], ...rest.slice(1)] : rest.slice(1); continue; }
    const operator = PS_OPERATOR.exec(rest[1] ?? '');
    if (!operator) return rest;
    rest = operator[1] ? [operator[1], ...rest.slice(2)] : rest.slice(2);
  }
}

// The arguments of the git invocation in one simple command (after assignments,
// keywords and wrappers), with the assignments that precede it; null when the command
// is not git.
function findGit(words, powershell = false) {
  if (powershell) words = skipPowerShellPrefix(words);
  const assignments = {};
  let i = 0;
  for (;;) {
    while (i < words.length && (ASSIGNMENT.test(words[i]) || SHELL_KEYWORDS.has(words[i]) || REDIRECTION.test(words[i]))) {
      if (ASSIGNMENT.test(words[i])) { const [k, ...v] = words[i].split('='); assignments[k] = v.join('='); }
      i += /^[0-9&]*[<>]+&?$/.test(words[i]) ? 2 : 1;
    }
    const name = commandName(words[i]);
    const valued = WRAPPERS[name];
    if (!valued) break;
    i += 1;
    while (i < words.length && words[i].startsWith('-')) i += valued.includes(words[i]) ? 2 : 1;
    if (name === 'timeout') i += 1; // `timeout [options] DURATION command`
  }
  if (commandName(words[i]) !== 'git') return null;
  return { args: words.slice(i + 1), assignments };
}

// Why this git invocation writes, or null when it only reads.
function writeReason({ args, assignments }) {
  const globals = [];
  let j = 0;
  while (j < args.length && args[j].startsWith('-')) {
    globals.push(args[j]);
    j += GIT_OPTIONS_WITH_VALUE.has(args[j]) ? 2 : 1;
  }
  const sub = args[j];
  if (sub === undefined) return null; // `git --version`, `git -C dir` alone
  const rest = args.slice(j + 1);
  if (flagNames(rest).includes('--output')) return `\`git ${sub} --output\` writes a file`;
  if (sub === 'status') {
    const quiet = globals.includes('--no-optional-locks') || assignments.GIT_OPTIONAL_LOCKS === '0';
    // A plain status refreshes and rewrites .git/index, and its lock can make a concurrent git
    // command fail. Other reads can refresh the index too (`git diff` on a stale stat cache):
    // only status, the common case, is singled out.
    return quiet ? null : 'a plain `git status` rewrites .git/index: use `git --no-optional-locks status`';
  }
  if (READ_ONLY.has(sub)) return null;
  if (READ_FORMS[sub] && READ_FORMS[sub](rest)) return null;
  return `\`git ${sub}\` can write repository state`;
}

let input;
try {
  input = JSON.parse(readFileSync(0, 'utf8'));
} catch {
  process.stderr.write('agent-git-guard: unreadable hook input (the wiring blocks it if it came from a delegated agent).\n');
  process.exit(FAILED);
}
// Bash, PowerShell and Monitor (which runs a shell command in the same environment): the
// shell tools, the three settings.json matches. Claude Code's EnterWorktree and
// ExitWorktree and a project's git MCP server also write git state, outside this guard; and
// a session that did not load the project's settings runs no guard at all (docs/04).
if (!['Bash', 'PowerShell', 'Monitor'].includes(input.tool_name) || !input.agent_id) process.exit(0);
const command = input.tool_input?.command;
if (input.tool_name === 'Monitor' && command === undefined) process.exit(0); // a WebSocket monitor runs no command
if (typeof command !== 'string') {
  process.stderr.write('agent-git-guard: no command in the hook input — blocking (fail-closed).\n');
  process.exit(BLOCKED);
}
// PowerShell ends a line at a CRLF. Bash does not: it keeps the \r as a character, and a
// backslash before a CRLF escapes the \r, not the line end — so its text is read as it
// is (a read with a stray \r then reads as a write: it fails safe).
const powershell = input.tool_name === 'PowerShell';
const reasons = splitCommands(powershell ? command.replace(/\r\n?/g, '\n') : command, powershell)
  .map((words) => findGit(words, powershell)).filter(Boolean).map(writeReason).filter(Boolean);
if (reasons.length) {
  process.stderr.write(
    `agent-git-guard: BLOCKED for a delegated agent (${input.agent_type ?? 'agent'}): ${[...new Set(reasons)].join('; ')}.\n`
    + 'Delegated agents are read-only on git (docs/04, "Delegated agents and the shared working tree").\n'
    + 'Read a revision with `git show <rev>:<path>`, `git diff <a>..<b>` or\n'
    + '`git archive <rev> | tar -x -C <a scratch dir outside the repo>`. Branches, commits and\n'
    + 'checkouts belong to the main session; pushes to the user.\n',
  );
  process.exit(BLOCKED);
}
process.exit(0);
